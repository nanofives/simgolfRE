      const hr = m.handle(h);                                // the stand-in handle record
      const bufp = hr.add(0x14).readPointer();              // H_BUF, the slot buffer
      // put `ready` bytes of fdr.dat into the handle buffer at offset 0, pchNext = buf, pchEndRead = buf + ready
      bufp.writeByteArray(m.data('fdr.dat').readByteArray(0x200));
      hr.add(0x24).writeU32(0);                              // H_NEXT
