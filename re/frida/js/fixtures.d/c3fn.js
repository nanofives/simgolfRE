  // a checksum of the 54 bits is): it writes 180 floats chosen by the context's first dword (OMS_FLOATS: 0 a ramp over
  // [-1.41, 1.39], 1 the special values, 2 signed by the bits, 3 zeros), so every clamp arm runs. Voice_resetDefaults (thunk
