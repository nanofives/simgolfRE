  // H_BOFF, so mmioSetInfo / mmioAdvance stay consistent). The ring R = [+8] is a second MMIOINFO (out.rings, 0x100 each):
  // pchBuffer +0x18 and pchEndWrite +0x24 bound a fixture ring buffer (out.rbufs, 0x200 each), +0x1c the read cursor, +0x20
  // the read end. +0x1378 the write cursor W, +0x1374 the mask, +0x170 position, +0x178 end, +0x1368 / +0x136c loop len /
  // start, +0x1b8 loop table, +0x13a0 a flag, +0x58 flags. The handle's buffer holds `avail` ready bytes from pchNext; when
  // a vector asks for more than that it is cut and mmioAdvance refills from fdr.dat (which is larger than the buffer).
  // rows: [+0x58, W offset in ring, mask, position, end, loop len, loop start, loop table?, +0x13a0, ready bytes, read
  //        cursor offset in ring, read end offset in ring]
  // ===================================================================================================================
  // rows 0-5 (key `a`) take the "free space <= bytes left" branch (0x100333cb not taken: the ring is filled to its free
  // space); rows 6-11 (key `b`) take "free space > bytes left" (0x100334db): only `rem` bytes remain. Within each, rows
  // vary the ring-end split, the file-buffer cut (small `ready`), the loop vs file-end bytes-left, the loop-rewind
  // (bit 2, no table, +0x13a0 clear, bit 7 clear) and the end-of-file flag (position reaching +0x178).
