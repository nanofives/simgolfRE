r"""c3fyc mutation campaign: build shim/src/re/c3fy_mut.inc = shim/src/re/c3fy.cpp with the mutants of
re/tools/c3fy_mutants.tsv applied (c3fy_negctl.cpp includes it; never linked into the main build).

Every mutant is dormant: it changes behaviour only when c3fyNegMode() (env SIMGOLF_C3FY_NEG, else the exported
c3fyNegCtl[0]) equals its id. Mode 9999 is the PROBE: every mutation site evaluates both the right and the wrong
version, keeps the right one, and logs the first time the two differ (`c3fyc-mut <id> infected frame <n>` in
simgolf_shim.log; for a dropped / swapped call or a skipped store whose value differs, reaching it is the infection). A
probe boot is the original behaviour (it must read SAME against the OFF reference) and tells which mutants a scenario can
see at all (weak mutation), so only infected (mutant, scenario) pairs need a strong ON vs OFF run.

Macros (inserted after c3fyNegMode in the copy):
  MV(id, right, wrong)        value mutant (both expressions side-effect free)
  MS(id) stmt;                stmt skipped when the mutant is active
  MSKIP(id, lhs, rhs);        store `lhs = rhs` skipped when active (probe: infected when the stored value differs)
  MI(id)                      true when active (swap: `if (MI(id)) { B A } else { A B }`)

    py -3.12 re/tools/c3fy_mutgen.py [--spec re/tools/c3fy_mutants.tsv] [--check]
"""
from __future__ import annotations

import argparse
import re
import sys

import c3fy_audit_common as A

OUT = A.ROOT / "shim" / "src" / "re" / "c3fy_mut.inc"
SPEC = A.ROOT / "re" / "tools" / "c3fy_mutants.tsv"

PRELUDE = r"""
// ---- c3fyc mutation campaign (generated by re/tools/c3fy_mutgen.py from re/tools/c3fy_mutants.tsv) ----
static volatile int c3fyFrame;                       // frames through the frame head (probe log only)
static unsigned char c3fyMutSeen[2048];
static void c3fyInfect(int id) {
    if (id >= 0 && id < 2048 && !c3fyMutSeen[id]) {
        c3fyMutSeen[id] = 1;
        ShimLog("c3fyc-mut %d infected frame %d", id, c3fyFrame);
    }
}
// active set for group runs (c3fyc): env SIMGOLF_C3FY_NEGSET = "id,id,..." activates every listed mutant at once
static unsigned char c3fySet[2048];
static int c3fySetRead = 0;
static bool c3fyOn(int id) {
    if (!c3fySetRead) {
        c3fySetRead = 1;
        char buf[4096];
        DWORD n = GetEnvironmentVariableA("SIMGOLF_C3FY_NEGSET", buf, sizeof buf);
        if (n > 0 && n < sizeof buf) {
            int v = -1;
            for (DWORD i = 0; i <= n; i++) {
                char ch = i < n ? buf[i] : ',';
                if (ch >= '0' && ch <= '9') v = (v < 0 ? 0 : v * 10) + (ch - '0');
                else { if (v >= 0 && v < 2048) c3fySet[v] = 1; v = -1; }
            }
        }
    }
    return (id >= 0 && id < 2048 && c3fySet[id]) || c3fyNegMode() == id;
}
static inline long long c3fyMVll(int id, long long r, long long w) {
    const int m = c3fyNegMode();
    if (c3fyOn(id)) return w;
    if (m == 9999 && r != w) c3fyInfect(id);
    return r;
}
static inline bool c3fyMS(int id) {               // false = skip the statement
    const int m = c3fyNegMode();
    if (c3fyOn(id)) return false;
    if (m == 9999) c3fyInfect(id);
    return true;
}
static inline bool c3fyMSkip(int id, bool differs) {
    const int m = c3fyNegMode();
    if (c3fyOn(id)) return false;
    if (m == 9999 && differs) c3fyInfect(id);
    return true;
}
static inline bool c3fyMI(int id) {
    const int m = c3fyNegMode();
    if (m == 9999) c3fyInfect(id);
    return c3fyOn(id);
}
#define MV(id, r, w) ((decltype((r) + 0))c3fyMVll((id), (long long)(r), (long long)(w)))
#define MS(id) if (!c3fyMS(id)) {} else
#define MSKIP(id, lhs, rhs) do { auto c3fyV_ = (rhs); if (c3fyMSkip((id), (long long)(lhs) != (long long)c3fyV_)) (lhs) = c3fyV_; } while (0)
#define MI(id) c3fyMI(id)
// ---- end of the campaign macros ----
"""


def load_spec(path):
    rows = []
    lines = path.read_text().splitlines()
    head = lines[0].split("\t")
    for ln in lines[1:]:
        if not ln.strip() or ln.startswith("#"):
            continue
        rows.append(dict(zip(head, ln.split("\t"))))
    return rows


def locate(lines, row, old):
    """the line holding `old` and citing the mutant's address, nearest to the recorded line number."""
    want = int(row["line"]) - 1
    va = int(row["va"], 16)
    tag = re.compile(rf"0x0*{va:x}\b", re.I)
    best = None
    for k in range(max(0, want - 400), min(len(lines), want + 400)):
        code = lines[k].split("//")[0]
        if old in code and tag.search(lines[k]):
            if best is None or abs(k - want) < abs(best - want):
                best = k
    return best


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--spec", default=str(SPEC))
    ap.add_argument("--src", default=str(A.SOURCE))
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--prune", action="store_true", help="drop the rows that do not apply from the spec")
    a = ap.parse_args()
    lines = A.pathlib.Path(a.src).read_text(encoding="utf-8").split("\n")
    rows = load_spec(A.pathlib.Path(a.spec))
    applied, failed = 0, []
    touched = set()
    for r in rows:
        mid, kind, old, new = r["id"], r["kind"], r["old"], r["new"]
        if kind == "swap":
            kb = locate(lines, r, new)          # B: the mutant's own line (the second call)
            if kb is None or kb - 1 < 0 or old not in lines[kb - 1].split("//")[0] or kb in touched or kb - 1 in touched:
                failed.append((mid, "swap anchors not found"))
                continue
            lines[kb - 1] = lines[kb - 1].replace(old, f"if (MI({mid})) {{ {new} {old} }} else {{ {old}", 1)
            lines[kb] = lines[kb].replace(new, f"{new} }}", 1)
            touched |= {kb, kb - 1}
            applied += 1
            continue
        k = locate(lines, r, old)
        if k is None or k in touched:
            failed.append((mid, "anchor not found" if k is None else "line already mutated"))
            continue
        code, sep, com = lines[k].partition("//")
        if kind == "const" and re.fullmatch(r"\(?(?:int\))?\s*(0x[0-9A-Fa-f]+|\d+)", old):
            pat = r"(?<![\w.])" + re.escape(old) + r"(?![\w.])"
            if len(re.findall(pat, code)) != 1:
                failed.append((mid, f"`{old}` not unique on line {k + 1}"))
                continue
            lines[k] = re.sub(pat, lambda m_: new, code, count=1) + sep + com
            touched.add(k)
            applied += 1
            continue
        if code.count(old) != 1:
            failed.append((mid, f"`{old}` occurs {code.count(old)} times on line {k + 1}"))
            continue
        lines[k] = code.replace(old, new, 1) + sep + com
        touched.add(k)
        applied += 1
    text = "\n".join(lines)
    # the campaign macros go right after c3fyNegMode (they call it); the frame counter at the frame head
    m = re.search(r"static int c3fyNegMode\(\) \{.*?\n\}\n#endif\n", text, re.S)
    if not m:
        raise SystemExit("c3fyNegMode block not found")
    text = text[:m.end()] + "#if defined(C3FY_NEG)\n" + PRELUDE + "#endif\n" + text[m.end():]
    fp = "            FramePreamble(F, retile);"
    if text.count(fp) != 1:
        raise SystemExit("frame head not found")
    text = text.replace(fp, "            ++c3fyFrame;\n" + fp)
    header = ("// GENERATED by re/tools/c3fy_mutgen.py from shim/src/re/c3fy.cpp + re/tools/c3fy_mutants.tsv: do not edit.\n"
              "// Included only by shim/src/re/c3fy_negctl.cpp (C3FY_NEG); never listed in shim/re_batches.txt.\n"
              "void ShimLog(const char* fmt, ...);\n")
    A.pathlib.Path(a.out).write_text(header + text, encoding="utf-8")
    print(f"{applied} mutants applied, {len(failed)} failed -> {a.out}")
    for f in failed:
        print("  FAILED", *f)
    if a.prune and failed:
        bad = {f[0] for f in failed}
        sp = A.pathlib.Path(a.spec)
        keep = [ln for ln in sp.read_text().splitlines() if ln.split("\t")[0] not in bad]
        sp.write_text("\n".join(keep) + "\n")
        print(f"  pruned {len(bad)} rows from {sp}")
        return 0
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
