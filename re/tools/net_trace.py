# ---------------------------------------------------------------- SDK headers -> tables
# Interfaces whose vtable layout the headers declare (an A interface shares its base's layout; dplay.h declares
# IDirectPlay2 / 3 / 4 and the A forms are the same struct with ANSI strings, dplobby.h likewise).
LAYOUT = {"IDirectPlay": "IDirectPlay", "IDirectPlay2": "IDirectPlay2", "IDirectPlay2A": "IDirectPlay2",
          "IDirectPlay3": "IDirectPlay3", "IDirectPlay3A": "IDirectPlay3", "IDirectPlay4": "IDirectPlay4",
          "IDirectPlay4A": "IDirectPlay4", "IDirectPlayLobby": "IDirectPlayLobby",
          "IDirectPlayLobbyA": "IDirectPlayLobby", "IDirectPlayLobby2": "IDirectPlayLobby2",
          "IDirectPlayLobby2A": "IDirectPlayLobby2", "IDirectPlayLobby3": "IDirectPlayLobby3",
          "IDirectPlayLobby3A": "IDirectPlayLobby3"}
# string charset per interface: IDirectPlay (v1) takes LPSTR names; the A forms are ANSI; the others Unicode
CHARSET = {n: ("A" if n.endswith("A") or n == "IDirectPlay" else "W") for n in LAYOUT}
# COM plumbing the headers above do not declare (objbase / unknwn layout, IIDs well known)
EXTRA_IFACES = {
    "IUnknown": [("QueryInterface", ["REFIID", "LPVOID *"]), ("AddRef", []), ("Release", [])],
    "IClassFactory": [("QueryInterface", ["REFIID", "LPVOID *"]), ("AddRef", []), ("Release", []),
                      ("CreateInstance", ["IUnknown *", "REFIID", "LPVOID *"]), ("LockServer", ["BOOL"])],
}
EXTRA_IIDS = {"IUnknown": "00000000-0000-0000-c000-000000000046",
              "IClassFactory": "00000001-0000-0000-c000-000000000046"}
EXTRA_EXPORTS = {"DirectPlayEnumerate": ["LPDPENUMDPCALLBACKA", "LPVOID"],
                 "DllGetClassObject": ["REFIID", "REFIID", "LPVOID *"], "DllCanUnloadNow": []}
_TYPE_WORDS = {"const", "CONST", "FAR", "far", "struct"}


def norm_type(t: str) -> str:
    """'LPVOID * ppvObj' -> 'LPVOID *', 'REFIID riid' -> 'REFIID', 'IUnknown *pUnk' -> 'IUnknown *'."""
    toks = [x for x in re.findall(r"\w+|\*", t) if x not in _TYPE_WORDS]
    if len(toks) > 1 and toks[-1] != "*" and (toks[-2] == "*" or re.fullmatch(r"[A-Z_][A-Z0-9_]*|[A-Za-z]\w*", toks[-2])):
        toks = toks[:-1]                                  # a trailing parameter name
    return " ".join(toks)


def _strip_comments(s: str) -> str:
    return re.sub(r"//[^\n]*", "", re.sub(r"/\*.*?\*/", "", s, flags=re.S))


def parse_headers(sdk: pathlib.Path = SDK) -> dict:
    """Interfaces (methods with parameter types, in slot order), IIDs, exports and callback typedefs."""
    src = "\n".join(_strip_comments((sdk / n).read_text(errors="replace")) for n in ("dplay.h", "dplobby.h"))
    ifaces = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{(.*?)\};", src, re.S):
        meths = []
        for mm in re.finditer(r"STDMETHOD(?:_\(\s*\w+\s*,\s*(\w+)\s*\)|\(\s*(\w+)\s*\))\s*\((.*?)\)\s*PURE", m.group(3), re.S):
            name = mm.group(1) or mm.group(2)
            args = [a.strip() for a in mm.group(3).split(",")]
            args[0] = re.sub(r"^THIS_?\s*", "", args[0])
            meths.append((name, [norm_type(a) for a in args if a.strip()]))
        ifaces[m.group(1)] = meths
    iids = {}
    for m in re.finditer(r"DEFINE_GUID\(\s*IID_(\w+)\s*,([^)]*)\)", src):
        v = [int(x.strip(), 0) for x in m.group(2).split(",")]
        iids[m.group(1)] = (f"{v[0]:08x}-{v[1]:04x}-{v[2]:04x}-{v[3]:02x}{v[4]:02x}-"
                            + "".join(f"{x:02x}" for x in v[5:]))
    exports = {}
    for m in re.finditer(r"extern\s+HRESULT\s+WINAPI\s+(\w+)\s*\((.*?)\)\s*;", src, re.S):
        exports[m.group(1)] = [norm_type(a) for a in m.group(2).split(",") if a.strip()]
    cbs = {}
    for m in re.finditer(r"typedef\s+BOOL\s*\(\s*(?:FAR\s+)?PASCAL\s*\*\s*(\w+)\s*\)\s*\((.*?)\)\s*;", src, re.S):
        cbs[m.group(1)] = [norm_type(a) for a in m.group(2).split(",") if a.strip()]
    return {"ifaces": ifaces, "iids": iids, "exports": exports, "cbs": cbs}


def struct_offsets(sdk: pathlib.Path, name: str) -> dict:
    """Member offsets of a 32-bit struct `typedef struct {...} NAME` (DWORD, pointers, GUID, unions of pointers)."""
    src = _strip_comments((sdk / "dplay.h").read_text(errors="replace"))
    m = re.search(r"typedef\s+struct\s*\w*\s*\{((?:[^{}]|\{[^{}]*\})*)\}\s*" + name + r"\b", src, re.S)
    if not m:
        raise KeyError(name)
    off, out = 0, {}
    for fm in re.finditer(r"union\s*\{([^{}]*)\}\s*;|(\w+)\s*(\*?)\s*(\w+)\s*;", m.group(1)):
        if fm.group(1) is not None:
            for nm in re.findall(r"(\w+)\s*;", fm.group(1)):
                out[nm] = off
            off += 4
            continue
        t, star, nm = fm.group(2), fm.group(3), fm.group(4)
        out[nm] = off
        off += 16 if (t == "GUID" and not star) else 4
    out["__size__"] = off
    return out


OUTOBJ_TYPES = {"LPDIRECTPLAY *": "IDirectPlay", "LPDIRECTPLAY2 *": "IDirectPlay2", "LPDIRECTPLAY2A *": "IDirectPlay2A",
                "LPDIRECTPLAYLOBBY *": "IDirectPlayLobby", "LPDIRECTPLAYLOBBYA *": "IDirectPlayLobbyA"}


def arg_kinds(types: list[str], cbs: dict) -> list[str]:
    """Recording kind per parameter (net_recordings.md section 3). The kind decides what the agent reads at entry
    and at return; it never decides how a record is parsed (items carry their own tags)."""
    out = []
    for i, t in enumerate(types):
        nxt = types[i + 1] if i + 1 < len(types) else ""
        prev = types[i - 1] if i else ""
        if t in ("DWORD", "DPID", "BOOL", "LONG", "ULONG", "UINT", "HRESULT"):
            k = "u"
        elif t in ("REFIID", "REFGUID", "LPGUID", "LPCGUID", "GUID *", "REFCLSID"):
            k = "g"
        elif t in OUTOBJ_TYPES:
            k = "o:" + OUTOBJ_TYPES[t]
        elif t == "LPVOID *":
            riid = [j for j in range(i) if types[j] in ("REFIID", "REFCLSID")]
            k = f"o@{riid[-1]}" if riid else "p"
        elif t in ("LPDPID", "LPDWORD"):
            k = "i"
        elif t in ("LPVOID", "LPCVOID") and nxt == "DWORD" and not (t == "LPVOID" and prev in cbs):
            k = f"b{i + 1}"
        elif t == "LPVOID" and nxt == "LPDWORD":
            k = f"B{i + 1}"
        elif t in ("LPDPSESSIONDESC2", "LPCDPSESSIONDESC2"):
            k = "sd"
        elif t in ("LPDPNAME", "LPCDPNAME"):
            k = "nm"
        elif t == "LPDPLCONNECTION":
            k = "cn"
        elif t == "LPDPCAPS":
            k = "cp"
        elif t == "LPDPSESSIONDESC":
            k = "sz"
        elif t in cbs:
            k = "c:" + t
        elif t in ("LPSTR", "LPCSTR"):
            k = "s"
        elif t in ("LPWSTR", "LPCWSTR"):
            k = "w"
        elif t in ("IUnknown *", "LPUNKNOWN"):
            k = "U"
        else:
            k = "p"
        out.append(k)
    return out


IFACE_ORDER = ["IUnknown", "IClassFactory", "IDirectPlay", "IDirectPlay2", "IDirectPlay2A", "IDirectPlay3", "IDirectPlay3A",
               "IDirectPlay4", "IDirectPlay4A", "IDirectPlayLobby", "IDirectPlayLobbyA", "IDirectPlayLobby2",
               "IDirectPlayLobby2A", "IDirectPlayLobby3", "IDirectPlayLobby3A"]


def ansi_out(kinds: list[str], cs: str) -> list[str]:
    """An ANSI interface or export hands out the A form of a typed out object (IDirectPlayLobbyA::Connect's
    LPDIRECTPLAY2 * is an IDirectPlay2A: same slots, ANSI strings); IDirectPlay (v1) has no A form."""
    if cs != "A":
        return kinds
    return [k + "A" if k.startswith("o:") and (k[2:] + "A") in LAYOUT else k for k in kinds]


def build_tables(sdk: pathlib.Path = SDK) -> dict:
    """Interface id = index + 1 in `ifaces` (0 = the DPLAYX exports); slot = vtable index; export id = index."""
    h = parse_headers(sdk)
    cbs = h["cbs"]
    ifaces = []
    for n in IFACE_ORDER:
        meths = EXTRA_IFACES[n] if n in EXTRA_IFACES else h["ifaces"][LAYOUT[n]]
        iid = EXTRA_IIDS.get(n) or h["iids"][n]
        cs = CHARSET.get(n, "A")
        ifaces.append({"name": n, "cs": cs, "iid": iid,
                       "slots": [[m, a, ansi_out(arg_kinds(a, cbs), cs)] for m, a in meths]})
    ex = dict(h["exports"])
    ex.update(EXTRA_EXPORTS)
    exports = [[n, ex[n], ansi_out(arg_kinds(ex[n], cbs), "W" if n.endswith("W") else "A")] for n in sorted(ex)]
    cbl = [[n, cbs[n], arg_kinds(cbs[n], cbs)] for n in sorted(cbs)]
    return {"ifaces": ifaces, "exports": exports, "cbs": cbl}


def tables_js(t: dict) -> str:
    d = lambda x: json.dumps(x, separators=(",", ":"))
    lines = [BEGIN_MARK, "const NR_TABLES = {", ' "ifaces": [']
    lines += ["  " + d(x) + ("," if i + 1 < len(t["ifaces"]) else "") for i, x in enumerate(t["ifaces"])]
    lines += [" ],", ' "exports": ' + d(t["exports"]) + ",", ' "cbs": ' + d(t["cbs"]), "};", END_MARK]
    return "\n".join(lines) + "\n"


def agent_block(path: pathlib.Path = AGENT) -> str | None:
    s = path.read_text(encoding="utf-8")
    a, b = s.find(BEGIN_MARK), s.find(END_MARK)
    if a < 0 or b < 0:
        return None
    return s[a:b + len(END_MARK)] + "\n"


def write_agent_block(block: str, path: pathlib.Path = AGENT):
    s = path.read_text(encoding="utf-8")
    a, b = s.find(BEGIN_MARK), s.find(END_MARK)
    path.write_text(s[:a] + block + s[b + len(END_MARK) + 1:], encoding="utf-8")


def tables_digest(block: str) -> str:
    return hashlib.sha256(block.encode()).hexdigest()


# ---------------------------------------------------------------- the file format (net_recordings.md section 2)
REC = {1: "MODULE", 2: "LOADLIB", 3: "GETPROC", 4: "CALL", 5: "RET", 6: "CB", 7: "CBRET", 8: "NEWOBJ", 0x7F: "END"}
RECN = {v: k for k, v in REC.items()}
TAG = {0: "U32", 1: "NULL", 2: "BYTES", 3: "STR", 4: "WSTR", 5: "OBJ", 6: "CB", 7: "PTR", 8: "GUID", 9: "STRUCT",
       10: "RELBYTES", 11: "BADPTR", 12: "OUTNULL"}
TAGN = {v: k for k, v in TAG.items()}
STRUCT_KIND = {1: "DPSESSIONDESC2", 2: "DPNAME", 3: "DPLCONNECTION", 4: "DPCAPS", 5: "SIZED"}


class NetTraceError(ValueError):
    pass


@dataclass
class Item:
    tag: str
    value: object = None                 # int, bytes, str, (kind, bytes, [Item]) for STRUCT, (bytes, [offsets]) RELBYTES

    def encode(self) -> bytes:
        t = TAGN[self.tag]
        v = self.value
        if self.tag in ("U32", "OBJ", "CB"):
            return struct.pack("<BI", t, v)
        if self.tag in ("NULL", "PTR", "BADPTR", "OUTNULL"):
            return bytes([t])
        if self.tag in ("BYTES", "STR", "WSTR"):
            b = v if isinstance(v, bytes) else (v.encode("latin-1") if self.tag == "STR" else v.encode("utf-16-le"))
            return struct.pack("<BI", t, len(b)) + b
        if self.tag == "GUID":
            return bytes([t]) + v
        if self.tag == "STRUCT":
            kind, b, subs = v
            return (struct.pack("<BBI", t, kind, len(b)) + b + bytes([len(subs)]) + b"".join(s.encode() for s in subs))
        if self.tag == "RELBYTES":
            b, fix = v
            return struct.pack("<BI", t, len(b)) + b + struct.pack("<H", len(fix)) + b"".join(struct.pack("<I", f) for f in fix)
        raise NetTraceError("unknown item tag " + self.tag)


def read_item(b: bytes, o: int) -> tuple[Item, int]:
    t = b[o]
    o += 1
    name = TAG.get(t)
    if name is None:
        raise NetTraceError(f"unknown item tag {t} at {o - 1}")
    if name in ("U32", "OBJ", "CB"):
        return Item(name, struct.unpack_from("<I", b, o)[0]), o + 4
    if name in ("NULL", "PTR", "BADPTR", "OUTNULL"):
        return Item(name), o
    if name in ("BYTES", "STR", "WSTR"):
        n = struct.unpack_from("<I", b, o)[0]
        raw = bytes(b[o + 4:o + 4 + n])
        v = raw if name == "BYTES" else (raw.decode("latin-1") if name == "STR" else raw.decode("utf-16-le", "replace"))
        return Item(name, v), o + 4 + n
    if name == "GUID":
        return Item(name, bytes(b[o:o + 16])), o + 16
    if name == "STRUCT":
        kind, n = struct.unpack_from("<BI", b, o)
        raw = bytes(b[o + 5:o + 5 + n])
        o += 5 + n
        cnt = b[o]
        o += 1
        subs = []
        for _ in range(cnt):
            it, o = read_item(b, o)
            subs.append(it)
        return Item(name, (kind, raw, subs)), o
    n = struct.unpack_from("<I", b, o)[0]           # RELBYTES
    raw = bytes(b[o + 4:o + 4 + n])
    o += 4 + n
    k = struct.unpack_from("<H", b, o)[0]
    fix = list(struct.unpack_from(f"<{k}I", b, o + 2))
    return Item(name, (raw, fix)), o + 2 + 4 * k


@dataclass
class Record:
    name: str
    sub: int
    f: dict = field(default_factory=dict)


def _str8(b: bytes, o: int) -> tuple[str, int]:
    n = b[o]
    return bytes(b[o + 1:o + 1 + n]).decode("latin-1"), o + 1 + n


def _items(b: bytes, o: int, n: int, indexed: bool) -> tuple[list, int]:
    out = []
    for _ in range(n):
        if indexed:
            i = b[o]
            it, o = read_item(b, o + 1)
            out.append((i, it))
        else:
            it, o = read_item(b, o)
            out.append(it)
    return out, o


def parse_record(t: int, sub: int, p: bytes) -> Record:
    name = REC.get(t)
    if name is None:
        raise NetTraceError(f"unknown record type 0x{t:02x}")
    f: dict = {}
    if name == "MODULE":
        f["pos"], f["thr"] = struct.unpack_from("<IB", p, 0)
        f["module"], o = _str8(p, 5)
    elif name == "LOADLIB":
        f["pos"], f["thr"], f["ra"], f["dp"] = struct.unpack_from("<IBIB", p, 0)
        f["lib"], o = _str8(p, 10)
    elif name == "GETPROC":
        f["pos"], f["thr"], f["ra"], f["dp"], f["byord"], f["ordinal"] = struct.unpack_from("<IBIBBI", p, 0)
        f["proc"], o = _str8(p, 15)
        f["export"] = p[o]
        o += 1
    elif name in ("CALL", "CB"):
        f["pos"], f["seq"], f["thr"] = struct.unpack_from("<IIB", p, 0)
        if name == "CALL":
            f["ra"], f["iface"], f["slot"], f["obj"], n = struct.unpack_from("<IBBIB", p, 9)
            o = 20
        else:
            f["fn"], f["cb"], n = struct.unpack_from("<IBB", p, 9)
            o = 15
        f["args"], o = _items(p, o, n, False)
    elif name in ("RET", "CBRET"):
        f["pos"], f["seq"], f["thr"], f["ret"], n = struct.unpack_from("<IIBIB", p, 0)
        f["out"], o = _items(p, 14, n, True)
    elif name == "NEWOBJ":
        f["pos"], f["obj"], f["iface"], f["seq"], f["how"] = struct.unpack_from("<IIBIB", p, 0)
        o = 14
    else:
        f["records"], f["calls"], f["cbs"], f["objs"] = struct.unpack_from("<4I", p, 0)
        o = 16
    if o != len(p):
        raise NetTraceError(f"{name}: payload {len(p)} bytes, parsed {o}")
    return Record(name, sub, f)


@dataclass
class NetTrace:
    meta: dict
    records: list


def header_bytes(meta: dict) -> bytes:
    m = json.dumps(meta, sort_keys=True, separators=(",", ":")).encode()
    return MAGIC + struct.pack("<HHII", VERSION, HEADER, len(m), 0) + m


def parse(data: bytes) -> NetTrace:
    if data[:8] != MAGIC:
        raise NetTraceError("bad magic")
    ver, hsz, mlen, _ = struct.unpack_from("<HHII", data, 8)
    if ver != VERSION or hsz != HEADER:
        raise NetTraceError(f"version {ver} header {hsz}")
    try:
        meta = json.loads(data[HEADER:HEADER + mlen])
    except ValueError as e:
        raise NetTraceError(f"meta: {e}") from e
    o, recs = HEADER + mlen, []
    while o < len(data):
        if o + 6 > len(data):
            raise NetTraceError(f"truncated record header at {o}")
        t, sub, n = struct.unpack_from("<BBI", data, o)
        if o + 6 + n > len(data):
            raise NetTraceError(f"truncated record at {o}")
        recs.append(parse_record(t, sub, data[o + 6:o + 6 + n]))
        o += 6 + n
    return NetTrace(meta, recs)


def read(path) -> NetTrace:
    return parse(pathlib.Path(path).read_bytes())


class Writer:
    """Synthetic NET.trace files for tests (the agent writes the same bytes, net_rec.js nrRec)."""

    def __init__(self, meta: dict):
        self.meta, self.body = meta, bytearray()

    def rec(self, name: str, sub: int, payload: bytes):
        self.body += struct.pack("<BBI", RECN[name], sub, len(payload)) + payload

    def bytes(self) -> bytes:
        return header_bytes(self.meta) + bytes(self.body)


def enc_items(items, indexed: bool = False) -> bytes:
    if indexed:
        return bytes([len(items)]) + b"".join(bytes([i]) + it.encode() for i, it in items)
    return bytes([len(items)]) + b"".join(it.encode() for it in items)


def validate(tr: NetTrace) -> list[str]:
    """net_recordings.md section 4."""
    e: list[str] = []
    m = tr.meta
    if m.get("net_schema") != VERSION:
        e.append(f"meta net_schema {m.get('net_schema')}")
    slots = m.get("slots") or []
    nex, ncb = m.get("nexports", 0), m.get("ncbs", 0)
    pos = 0
    seq = 0
    open_calls: dict = {}
    nobj = 0
    threads = 1
    counts = {"calls": 0, "cbs": 0}
    for i, r in enumerate(tr.records):
        f = r.f
        if r.name == "END":
            if i != len(tr.records) - 1:
                e.append(f"record {i}: END is not last")
            want = {"records": i, "calls": counts["calls"], "cbs": counts["cbs"], "objs": nobj}
            got = {k: f[k] for k in want}
            if got != want:
                e.append(f"END totals {got} != {want}")
            continue
        if f.get("pos", pos) < pos:
            e.append(f"record {i} {r.name}: pos {f['pos']} < {pos}")
        pos = max(pos, f.get("pos", pos))
        if "thr" in f:
            if f["thr"] > threads:
                e.append(f"record {i}: thread ordinal {f['thr']} skips (next new is {threads})")
            threads = max(threads, f["thr"] + 1)
        if r.name in ("CALL", "CB"):
            if f["seq"] != seq:
                e.append(f"record {i} {r.name}: seq {f['seq']} != {seq}")
            seq = f["seq"] + 1
            open_calls[f["seq"]] = r.name
            counts["calls" if r.name == "CALL" else "cbs"] += 1
            if r.name == "CALL":
                if f["iface"] == 0:
                    if f["slot"] >= nex or f["obj"] != 0xFFFFFFFF:
                        e.append(f"record {i}: export call slot {f['slot']} obj {f['obj']:#x}")
                elif f["iface"] > len(slots) or f["slot"] >= slots[f["iface"] - 1]:
                    e.append(f"record {i}: iface {f['iface']} slot {f['slot']} outside the tables")
                elif f["obj"] >= nobj:
                    e.append(f"record {i}: object {f['obj']} not created yet")
            elif f["cb"] >= ncb:
                e.append(f"record {i}: callback kind {f['cb']} outside the tables")
        elif r.name in ("RET", "CBRET"):
            want = "CALL" if r.name == "RET" else "CB"
            if open_calls.pop(f["seq"], None) != want:
                e.append(f"record {i} {r.name}: seq {f['seq']} has no open {want}")
        elif r.name == "NEWOBJ":
            if f["obj"] != nobj:
                e.append(f"record {i}: NEWOBJ {f['obj']} != {nobj}")
            nobj += 1
            if not 1 <= f["iface"] <= len(slots):
                e.append(f"record {i}: NEWOBJ iface {f['iface']}")
    if not tr.records or tr.records[-1].name != "END":
        e.append("no END record")
    return e


def method_name(meta: dict, iface: int, slot: int) -> str:
    if iface == 0:
        ex = meta.get("exports") or []
        return ex[slot] if slot < len(ex) else f"export#{slot}"
    names, meths = meta.get("ifaces") or [], meta.get("methods") or []
    if iface - 1 < len(meths) and slot < len(meths[iface - 1]):
        return f"{names[iface - 1]}::{meths[iface - 1][slot]}"
    return f"iface{iface}#{slot}"


def summary(tr: NetTrace) -> dict:
    by_type: dict = {}
    by_method: dict = {}
    payload = {"send_bytes": 0, "receive_bytes": 0, "sends": 0, "receives": 0}
    calls = {}
    for r in tr.records:
        by_type[r.name] = by_type.get(r.name, 0) + 1
        if r.name == "CALL":
            n = method_name(tr.meta, r.f["iface"], r.f["slot"])
            by_method[n] = by_method.get(n, 0) + 1
            calls[r.f["seq"]] = n
            if n.endswith("::Send"):
                payload["sends"] += 1
                payload["send_bytes"] += sum(len(a.value) for a in r.f["args"] if a.tag == "BYTES")
        elif r.name == "RET" and calls.get(r.f["seq"], "").endswith("::Receive") and r.f["ret"] == 0:
            payload["receives"] += 1
            payload["receive_bytes"] += sum(len(it.value[0]) for _, it in r.f["out"] if it.tag == "RELBYTES")
    threads = sorted({r.f["thr"] for r in tr.records if "thr" in r.f})
    return {"records": len(tr.records), "by_type": by_type, "by_method": dict(sorted(by_method.items())),
            "threads": threads, **payload, "meta_scenario": tr.meta.get("scenario")}


def fmt_item(it: Item) -> str:
    if it.tag in ("U32", "OBJ", "CB"):
        return f"{it.tag}:{it.value:#x}"
    if it.tag in ("STR", "WSTR"):
        return f"{it.tag}:{it.value!r}"
    if it.tag == "BYTES":
        return f"BYTES[{len(it.value)}]:{it.value[:32].hex()}"
    if it.tag == "GUID":
        return "GUID:" + it.value.hex()
    if it.tag == "STRUCT":
        k, b, subs = it.value
        return f"{STRUCT_KIND.get(k, k)}[{len(b)}]:{b.hex()}{{{', '.join(fmt_item(s) for s in subs)}}}"
    if it.tag == "RELBYTES":
        b, fix = it.value
        return f"RELBYTES[{len(b)} fix {len(fix)}]:{b[:32].hex()}"
    return it.tag


def fmt_record(meta: dict, r: Record) -> str:
    f = dict(r.f)
    head = f"{r.name:7s} pos {f.pop('pos', '-')}"
    if r.name == "CALL":
        head += f" seq {f['seq']} thr {f['thr']} ra {f['ra']:#010x} {method_name(meta, f['iface'], f['slot'])} obj {f['obj']:#x}"
        return head + " (" + ", ".join(fmt_item(a) for a in f["args"]) + ")"
    if r.name == "CB":
        cbs = meta.get("cbs") or []
        head += f" seq {f['seq']} thr {f['thr']} fn {f['fn']:#010x} {cbs[f['cb']] if f['cb'] < len(cbs) else f['cb']}"
        return head + " (" + ", ".join(fmt_item(a) for a in f["args"]) + ")"
    if r.name in ("RET", "CBRET"):
        outs = ", ".join(f"a{i}={fmt_item(it)}" for i, it in f["out"])
        return head + f" seq {f['seq']} thr {f['thr']} -> {f['ret']:#x} {outs}"
    return head + " " + " ".join(f"{k}={v:#x}" if isinstance(v, int) and k == "ra" else f"{k}={v}" for k, v in f.items())


def diff(a: NetTrace, b: NetTrace) -> dict:
    """First differing record (by encoded content; meta compared apart)."""
    out: dict = {}
    if a.meta != b.meta:
        out["meta"] = sorted(k for k in set(a.meta) | set(b.meta) if a.meta.get(k) != b.meta.get(k))
    for i, (x, y) in enumerate(zip(a.records, b.records)):
        if x != y:
            out.update(where=i, a=fmt_record(a.meta, x), b=fmt_record(b.meta, y))
            return out
    if len(a.records) != len(b.records):
        out.update(where=min(len(a.records), len(b.records)), a_records=len(a.records), b_records=len(b.records))
    return out


def called_methods(tr: NetTrace) -> dict:
    out: dict = {}
    for r in tr.records:
        if r.name == "CALL":
            n = method_name(tr.meta, r.f["iface"], r.f["slot"])
            out[n] = out.get(n, 0) + 1
    return out


def need_list(path: pathlib.Path) -> list[str]:
    """Methods a survey names: any TSV cell of the form Iface::Method or a DPLAYX export name."""
    names = set()
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    head = lines[0].split("\t") if lines else []
    col = head.index("dp_calls") if "dp_calls" in head else -1
    for line in lines[1:] if col >= 0 else []:
        cells = line.split("\t")
        for part in (cells[col].split(";") if col < len(cells) else []):
            m = re.fullmatch(r"\s*(\w+)\s+x\d+\s*", part)      # S9.1's form `Send x3`: a method of the DirectPlay object
            if m:
                names.add("*::" + m.group(1))
    for line in lines:
        for cell in line.split("\t"):
            for m in re.finditer(r"\b(IDirectPlay\w*|IClassFactory|IUnknown)::(\w+)|\b(DirectPlay\w+|DllGetClassObject)\b", cell):
                names.add(m.group(0))
    return sorted(names)


def table_names(t: dict) -> set:
    s = {f"{x['name']}::{m[0]}" for x in t["ifaces"] for m in x["slots"]}
    s |= {f"*::{m[0]}" for x in t["ifaces"] if x["name"].startswith("IDirectPlay") for m in x["slots"]}
    return s | {e[0] for e in t["exports"]}


def meta_for(t: dict, scenario: str, block: str) -> dict:
    """The meta block the agent writes (net_rec.py passes it the same values)."""
    return {"net_schema": VERSION, "scenario": scenario, "tables": tables_digest(block),
            "ifaces": [x["name"] for x in t["ifaces"]], "slots": [len(x["slots"]) for x in t["ifaces"]],
            "methods": [[m[0] for m in x["slots"]] for x in t["ifaces"]],
            "exports": [e[0] for e in t["exports"]], "nexports": len(t["exports"]),
            "cbs": [c[0] for c in t["cbs"]], "ncbs": len(t["cbs"]), "spec": "re/analysis/net/net_recordings.md"}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("tables")
    p.add_argument("--sdk", default=str(SDK))
    p.add_argument("--write", action="store_true", help="replace the block in re/frida/js/net_rec.js")
    sp.add_parser("check-tables").add_argument("--sdk", default=str(SDK))
    sp.add_parser("validate").add_argument("files", nargs="+")
    p = sp.add_parser("summary")
    p.add_argument("file")
    p.add_argument("--json", action="store_true")
    p = sp.add_parser("dump")
    p.add_argument("file")
    p.add_argument("--types")
    p.add_argument("--from", dest="start", type=int, default=0)
    p.add_argument("--limit", type=int, default=0)
    p = sp.add_parser("diff")
    p.add_argument("a")
    p.add_argument("b")
    p = sp.add_parser("coverage")
    p.add_argument("files", nargs="*")
    p.add_argument("--need", default=str(ROOT / "re" / "port" / "net_functions.tsv"))
    a = ap.parse_args(argv)
    if a.cmd == "tables":
        block = tables_js(build_tables(pathlib.Path(a.sdk)))
        if a.write:
            write_agent_block(block)
        else:
            sys.stdout.write(block)
        return 0
    if a.cmd == "check-tables":
        ok = agent_block() == tables_js(build_tables(pathlib.Path(a.sdk)))
        print("agent tables == SDK headers" if ok else "agent tables DIFFER from the SDK headers (run: tables --write)")
        return 0 if ok else 1
    if a.cmd == "validate":
        rc = 0
        for f in a.files:
            try:
                errs = validate(read(f))
            except NetTraceError as e:
                errs = [f"parse: {e}"]
            print(f"{f}: {'OK' if not errs else 'INVALID'}")
            for x in errs[:20]:
                print("  " + x)
            rc |= bool(errs)
        return rc
    if a.cmd == "summary":
        s = summary(read(a.file))
        print(json.dumps(s, indent=1) if a.json else "\n".join(f"{k:16s} {v}" for k, v in s.items()))
        return 0
    if a.cmd == "dump":
        tr = read(a.file)
        want = set(a.types.upper().split(",")) if a.types else None
        shown = 0
        for i, r in enumerate(tr.records):
            if i < a.start or (want and r.name not in want):
                continue
            print(f"{i:7d} {fmt_record(tr.meta, r)}")
            shown += 1
            if a.limit and shown >= a.limit:
                break
        return 0
    if a.cmd == "diff":
        da, db = pathlib.Path(a.a).read_bytes(), pathlib.Path(a.b).read_bytes()
        if da == db:
            print(f"byte-identical ({len(da)} bytes)")
            return 0
        print(json.dumps(diff(parse(da), parse(db)), indent=1))
        return 1
    # coverage: what a survey names against the agent's tables and against recordings
    t = build_tables() if SDK.exists() else None
    need = need_list(pathlib.Path(a.need)) if pathlib.Path(a.need).exists() else []
    seen: dict = {}
    for f in a.files:
        for k, v in called_methods(read(f)).items():
            seen[k] = seen.get(k, 0) + v
    known = table_names(t) if t else set()
    for n in need:
        hit = n in seen or (n.startswith("*::") and any(k.endswith(n[1:]) for k in seen))
        print(f"{n:48s} tables {'yes' if (n in known or not t) else 'NO'}  recorded {'yes' if hit else '-'}")
    for k in sorted(k for k in seen if k not in need and "*::" + k.split("::")[-1] not in need):
        print(f"{k:48s} recorded {seen[k]} (not in the survey list)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
