r"""NET.trace: the DirectPlay call side file of a schema v1 trace (roadmap S9.2, 2026-10-29).

Format and recording rules: re/analysis/net/net_recordings.md. Writer: re/frida/js/net_rec.js (appended after
scenario_det.js + trace_rec.js by re/tools/net_rec.py). This module reads, validates, summarises, dumps and diffs
NET.trace files, and generates the agent's interface / slot tables from the DirectX 8 SDK headers in tools/dxsdk8
(dplay.h, dplobby.h; local, not committed), so a static test can check the agent's table against the headers.

    ~/bin/py -3.12 re/tools/net_trace.py tables [--sdk tools/dxsdk8/include]      # print the generated JS table block
    ~/bin/py -3.12 re/tools/net_trace.py check-tables                              # agent block == generated? exit 1 if not
    ~/bin/py -3.12 re/tools/net_trace.py validate <file>...
    ~/bin/py -3.12 re/tools/net_trace.py summary <file> [--json]
    ~/bin/py -3.12 re/tools/net_trace.py dump <file> [--types CALL,RET] [--from N] [--limit N]
    ~/bin/py -3.12 re/tools/net_trace.py diff <a> <b>
    ~/bin/py -3.12 re/tools/net_trace.py coverage <file> [--functions re/port/net_functions.tsv]

trace_format.py and trace_rec.js are not changed by this side file; the shared key is the schema v1 position (the
number of main-thread clock calls before the record, trace_schema.md section 1).
"""
