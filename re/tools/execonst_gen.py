r"""Generate port/include/portsim/execonst_desc.inc: the exe-constant descriptors the port reads from the user's own exe
(phase 3.0, 2026-10-19; decision re/model/DECISIONS.md: constants stay in the user's exe, the model records descriptors).

One X-macro row per row of re/model/f_descriptors.tsv (stride `var`, string pools, is written as 0):

    SG_EXE_CONST(symbol, file_offset, size, "element_type", count, stride, "kind", hash)

`hash` is sgh64 (re/tools/state_image.py) of the descriptor's bytes in the anchored golf_clean.exe (re/anchors.json), in
DECIMAL so no hex literal of the original's address range appears in port code. portsim::ExeConstants checks every hash
when it loads an exe, so a different build is refused by name instead of read wrong. No table byte or string is copied
into the port: only offsets, sizes, types and hashes.

The descriptor's `va` column is NOT emitted (port code holds no original address); the file offset locates the bytes.

    ~/bin/py -3.12 re/tools/execonst_gen.py           # write the .inc
    ~/bin/py -3.12 re/tools/execonst_gen.py --check   # exit 1 when the committed .inc is stale
"""
from __future__ import annotations

import argparse
import csv
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "re" / "tools"))
import state_image as SI  # noqa: E402

DESC = ROOT / "re" / "model" / "f_descriptors.tsv"
EXE = ROOT / "original" / "golf_clean.exe"
OUT = ROOT / "port" / "include" / "portsim" / "execonst_desc.inc"


def rows() -> list[dict]:
    with DESC.open(newline="") as f:
        return list(csv.DictReader(f, delimiter="\t"))


def render(exe: bytes) -> str:
    out = [
        "// GENERATED by re/tools/execonst_gen.py from re/model/f_descriptors.tsv and the anchored golf_clean.exe. Do not edit.",
        "// SG_EXE_CONST(symbol, file_offset, size, element_type, count, stride, kind, sgh64 of the bytes in the anchored exe)",
        "// Offsets and hashes only: no byte of the original is in this file (portsim/execonst.h).",
    ]
    for r in rows():
        off, size = int(r["file_offset"], 16), int(r["size"], 16)
        blob = exe[off:off + size]
        if len(blob) != size:
            raise SystemExit(f"{r['symbol']}: file range 0x{off:x}+0x{size:x} outside the exe")
        h = SI.sgh64(blob)
        out.append(f'SG_EXE_CONST({r["symbol"]}, {off}u, {size}u, "{r["element_type"]}", {int(r["count"])}u, '
                   f'{0 if r["stride"] == "var" else int(r["stride"])}u, "{r["kind"]}", {h}ull)')
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(EXE.read_bytes())
    if a.check:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("execonst_desc.inc", "up to date" if ok else "STALE")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count('SG_EXE_CONST(') - 1} descriptors")
    return 0


if __name__ == "__main__":
    sys.exit(main())
