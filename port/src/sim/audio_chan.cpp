// ---- ChannelTable_callSlot4 (rva 0x1ae50): hand-fixed conversion of c3fk.cpp CallSlot4_re
uint32_t ChannelTable_callSlot4_body(Ctx &ctx, u32 self, uint32_t v) {
    u32 last = 0;  // 0x1ae5f
    for (int k = 0; k < 0x80; ++k) {  // 0x1ae61 / 0x1ae64 / 0x1aeba
        const u32 slot = self + 4 + 4 * static_cast<u32>(k);
        u32 o = ld<u32>(ctx, slot);  // 0x1ae6c
        if (!o || o == last) continue;  // 0x1ae6e-0x1ae74
        snd_vcall(ctx, o, 4, SndAbi::Thiscall, {v});  // 0x1ae76-0x1ae79
        o = ld<u32>(ctx, slot);  // 0x1ae7c
        for (int j = 0; j < sub32(ld<int32_t>(ctx, o + 0x1438), 1); ++j) {  // 0x1ae80-0x1ae89, 0x1aea1-0x1aeaa
            u32 m = ld<u32>(ctx, o + 0x1440 + 4 * static_cast<u32>(j));  // 0x1ae90
            snd_vcall(ctx, m, 4, SndAbi::Thiscall, {v});  // 0x1ae93-0x1ae98
            o = ld<u32>(ctx, slot);  // 0x1ae9b
        }
        last = ld<u32>(ctx, slot);  // 0x1aeac
    }
    st<uint32_t>(ctx, self + 0x218, v);  // 0x1aec2
    return last;
}
