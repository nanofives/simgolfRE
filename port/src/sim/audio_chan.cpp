// The per-voice gain step Channel_recomputeVoiceGains, Channel_setRate and Channel_setReverseRate share (Gains's addresses; the
// other two are given at their call sites): with the engine rate R (slot +0x40) and the channel rate r, fild qword both
// (0x3549f / 0x354a7), fcom (0x354ab) and, only when r > R (`test ah, 0x41; jne`, 0x354b2): q = r / R (fdivrp 0x354b4), the
// voice's +0 word = __ftol(fild dword [s-0x9c] / q) (0x354b6-0x354be) and d = [s-0x94] / q (fdivr 0x354c3); otherwise the
// word is [s-0x9c] and d = [s-0x94] (0x354cd-0x354dd). Returns the value stored and leaves d in out (the caller stores it
// with fst / fstp). Mode 2 (x87 wrong port): the quotients are computed as plain doubles.
int32_t voiceGainStep(Ctx &ctx, u32 s, uint32_t R, uint32_t r, X80 &out) {
    X80 A, B, q, v, d;
    x_ldU32(ctx, A, R);
    x_ldU32(ctx, B, r);
    if ((x_com(ctx, B, A) >> 8) & 0x41) {
        x_ld(ctx, out, s - 0x94);
        return ld<int32_t>(ctx, s - 0x9c);
    }
    x_div(ctx, q, B, A);
    x_ldI32(ctx, v, ld<int32_t>(ctx, s - 0x9c));
    x_div(ctx, v, v, q);
    int32_t w = x_ftol(ctx, v);
    x_ld(ctx, d, s - 0x94);
    x_div(ctx, out, d, q);
    return w;
}
