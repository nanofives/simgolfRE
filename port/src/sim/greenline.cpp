// blendFaceTextures' piece from three edge kinds (terrain_state.cpp flag_code + id_class, the same table)
int32_t piece_of(int32_t a, int32_t b, int32_t c) {
  int32_t r = 0;
  r += a == 1 ? 4 : a == 2 ? 0x28 : 0;
  r += b == 1 ? 1 : b == 2 ? 10 : 0;
  r += c == 1 ? 2 : c == 2 ? 0x14 : 0;
  switch (r) {
    case 3: case 0x2b: return 2;
    case 4: case 0xe: case 0x18: case 0x22: return 4;
    case 5: case 7: case 0x19: return 3;
    case 6: case 0x10: return 1;
    case 0x28: case 0x29: case 0x2a: case 0x3d: return 8;
    case 0x32: case 0x34: case 0x46: return 7;
    case 0x3c: return 5;
    case 0x1e: return 6;
    default: return 0;
  }
}

// the tile's 64 x 64 bright texels (row r along y, bit c along x): face by face, the piece blendFaceTextures gives it. A face is
// the half of a quadrant toward one side a (the one the texel centre is nearer; the diagonal goes to the y side), its piece from
// the edge kinds toward a, toward the quadrant's other side b and toward the corner's diagonal tile c; edgeKind: 0 off the map or
// the same type, 1 another collar group, 2 the same group and another type (terrain_state.cpp edge_kind; the collar groups are the
// table the exe passes, terrain_dll.cpp collar_table). Pieces 5 .. 8 have no texture for the green (no file): no band there.
void tile_mask(Ctx &ctx, int32_t x, int32_t y, uint64_t out[64]) {
  const int32_t last = world_last(ctx);
  const uint8_t course = static_cast<uint8_t>(ctx.gs().g_courseType);
  auto collar = [&](int32_t t) -> int32_t {
    if (t < 0 || t >= 23) return 0x100 + t;   // outside the exe's 23-entry table: a group of its own
    const Ptr<TileTypeAttr> at = state_arr(ctx, &GameState::g_tileTypeAttrs) + t;
    if (course == 1 && at.field(&TileTypeAttr::walk).get() > 0 && t != 5 && t != 7) return 4;
    return at.field(&TileTypeAttr::collar).get();
  };
  const int32_t own = terrain_tile_type(ctx, x, y), own_c = collar(own);
  auto kind = [&](int32_t dx, int32_t dy) {
    const int32_t nx = x + dx, ny = y + dy;
    if (nx < 0 || ny < 0 || nx > last || ny > last) return 0;
    const int32_t t = terrain_tile_type(ctx, nx, ny);
    if (collar(t) != own_c) return 1;
    return t != own ? 2 : 0;
  };
  int32_t pa[2][2], pb[2][2];   // [qx][qy]: the face toward the y side (a = y side), the face toward the x side
  for (int qx = 0; qx < 2; ++qx)
    for (int qy = 0; qy < 2; ++qy) {
      const int32_t sx = qx ? 1 : -1, sy = qy ? 1 : -1;
      const int32_t ky = kind(0, sy), kx = kind(sx, 0), kd = kind(sx, sy);
      pa[qx][qy] = piece_of(ky, kx, kd);
      pb[qx][qy] = piece_of(kx, ky, kd);
    }
  for (int r = 0; r < 64; ++r) {
    uint64_t row = 0;
    const int qy = r >= 32 ? 1 : 0, dy = qy ? 63 - r : r;   // texel rows from the nearer y side
    for (int c = 0; c < 64; ++c) {
      const int qx = c >= 32 ? 1 : 0, dx = qx ? 63 - c : c;
      const int32_t p = dy <= dx ? pa[qx][qy] : pb[qx][qy];
      const bool lit = p > 4 || ((kGreenPieceMask[p][r] >> c) & 1u) != 0;
      if (lit) row |= 1ull << c;
    }
    out[r] = row;
  }
}

// a closed lattice loop simplified (Douglas-Peucker within tol texels), vertex list without the repeated start
void simplify_loop(const std::vector<std::pair<int32_t, int32_t>> &in, double tol, std::vector<std::pair<int32_t, int32_t>> &out) {
  out.clear();
  const size_t n = in.size();
  if (n < 3) {
    out = in;
    return;
  }
  // the two vertices farthest apart split the loop into two open chains
  size_t a = 0, b = 0;
  int64_t best = -1;
  for (size_t i = 0; i < n; ++i) {
    const int64_t dx = in[i].first - in[0].first, dy = in[i].second - in[0].second;
    if (dx * dx + dy * dy > best) {
      best = dx * dx + dy * dy;
      b = i;
    }
  }
  std::vector<uint8_t> keep(n, 0);
  keep[a] = keep[b] = 1;
  std::vector<std::pair<size_t, size_t>> work{{a, b}, {b, n}};   // index n stands for 0 again
  auto at = [&](size_t i) { return in[i % n]; };
  while (!work.empty()) {
    const auto [i0, i1] = work.back();
    work.pop_back();
    if (i1 <= i0 + 1) continue;
    const double x0 = at(i0).first, y0 = at(i0).second, x1 = at(i1).first, y1 = at(i1).second;
    const double ex = x1 - x0, ey = y1 - y0, len = std::hypot(ex, ey);
    double dmax = -1;
    size_t im = i0;
    for (size_t i = i0 + 1; i < i1; ++i) {
      const double px = at(i).first - x0, py = at(i).second - y0;
      const double d = len > 0 ? std::fabs(ex * py - ey * px) / len : std::hypot(px, py);
      if (d > dmax) {
        dmax = d;
        im = i;
      }
    }
    if (dmax > tol) {
      keep[im % n] = 1;
      work.push_back({i0, im});
      work.push_back({im, i1});
    }
  }
  for (size_t i = 0; i < n; ++i)
    if (keep[i]) out.push_back(in[i]);
}

void build_shape(Ctx &ctx, GreenOutline &o) {
  if (o.tiles.empty()) return;
  const int32_t N = world_n(ctx);
  int32_t X0 = 1 << 30, Y0 = 1 << 30, X1 = -1, Y1 = -1;
  for (int32_t i : o.tiles) {
    X0 = std::min(X0, i / N);
    X1 = std::max(X1, i / N);
    Y0 = std::min(Y0, i % N);
    Y1 = std::max(Y1, i % N);
  }
  const int32_t W = (X1 - X0 + 1) * 64, H = (Y1 - Y0 + 1) * 64;
  std::vector<uint8_t> lit(static_cast<size_t>(W) * H, 0);
  for (int32_t i : o.tiles) {
    const int32_t x = i / N, y = i % N;
    uint64_t m[64];
    tile_mask(ctx, x, y, m);
    const int32_t gx = (x - X0) * 64, gy = (y - Y0) * 64;
    for (int r = 0; r < 64; ++r)
      for (int c = 0; c < 64; ++c)
        if ((m[r] >> c) & 1u) lit[static_cast<size_t>(gy + r) * W + gx + c] = 1;
    // the strips: runs of each row, rows with the same texels merged
    int r0 = 0;
    for (int r = 1; r <= 64; ++r) {
      if (r < 64 && m[r] == m[r0]) continue;
      const uint64_t row = m[r0];
      for (int c = 0; c < 64;) {
        if (!((row >> c) & 1u)) {
          ++c;
          continue;
        }
        int e = c;
        while (e < 64 && ((row >> e) & 1u)) ++e;
        o.strips.push_back(GreenEdge{(x << 10) + 16 * c, (y << 10) + 16 * r0, (x << 10) + 16 * e, (y << 10) + 16 * r});
        c = e;
      }
      r0 = r;
    }
  }
  // the boundary: every side of a lit texel toward an unlit one, directed with the lit texel on its left in x / y order, joined
  // into loops (at a vertex with two ways on, the left turn: diagonal texels stay apart), simplified within a texel
  auto L = [&](int32_t gx, int32_t gy) { return gx >= 0 && gy >= 0 && gx < W && gy < H && lit[static_cast<size_t>(gy) * W + gx]; };
  const int32_t VW = W + 1;
  std::vector<std::array<int32_t, 2>> next(static_cast<size_t>(VW) * (H + 1), std::array<int32_t, 2>{-1, -1});
  auto add = [&](int32_t ax, int32_t ay, int32_t bx, int32_t by) {
    std::array<int32_t, 2> &s = next[static_cast<size_t>(ay) * VW + ax];
    s[s[0] < 0 ? 0 : 1] = by * VW + bx;
  };
  for (int32_t gy = 0; gy < H; ++gy)
    for (int32_t gx = 0; gx < W; ++gx) {
      if (!L(gx, gy)) continue;
      if (!L(gx, gy - 1)) add(gx, gy, gx + 1, gy);
      if (!L(gx + 1, gy)) add(gx + 1, gy, gx + 1, gy + 1);
      if (!L(gx, gy + 1)) add(gx + 1, gy + 1, gx, gy + 1);
      if (!L(gx - 1, gy)) add(gx, gy + 1, gx, gy);
    }
  std::vector<std::pair<int32_t, int32_t>> loop, simple;
  for (size_t v0 = 0; v0 < next.size(); ++v0) {
    while (next[v0][0] >= 0) {
      loop.clear();
      int32_t v = static_cast<int32_t>(v0), px = -1, py = -1;
      for (;;) {
        std::array<int32_t, 2> &s = next[static_cast<size_t>(v)];
        if (s[0] < 0) break;
        const int32_t vx = v % VW, vy = v / VW;
        int k = 0;
        if (s[1] >= 0 && px >= 0) {   // two ways on: the left turn of the way in (x / y order: (dx, dy) -> (-dy, dx))
          const int32_t dx = vx - px, dy = vy - py;
          const int32_t w1x = s[1] % VW - vx, w1y = s[1] / VW - vy;
          if (w1x == -dy && w1y == dx) k = 1;
        }
        const int32_t w = s[k];
        s[k] = s[1 - k];
        s[1 - k] = -1;
        loop.push_back({vx, vy});
        px = vx;
        py = vy;
        v = w;
        if (v == static_cast<int32_t>(v0)) break;   // the loop closed
      }
      simplify_loop(loop, 1.0, simple);
      for (size_t i = 0; i < simple.size(); ++i) {
        const auto &a = simple[i], &b = simple[(i + 1) % simple.size()];
        o.shape.push_back(GreenEdge{(X0 << 10) + 16 * a.first, (Y0 << 10) + 16 * a.second, (X0 << 10) + 16 * b.first,
                                    (Y0 << 10) + 16 * b.second});
      }
    }
  }
}

// a shape or strip point's tile for worldToScreen: a point on a tile side whose tile is not in the set is moved one unit back into
// the neighbour that is (its height then comes from a green tile's corners, as the ground under it is drawn)
void shape_point(const GreenOutline &o, int32_t N, int32_t &wx, int32_t &wy) {
  auto in = [&](int32_t x, int32_t y) { return x >= 0 && y >= 0 && x < N && y < N && std::binary_search(o.tiles.begin(), o.tiles.end(), x * N + y); };
  const int32_t tx = wx >> 10, ty = wy >> 10;
  if (in(tx, ty)) return;
  const bool ex = (wx & 1023) == 0, ey = (wy & 1023) == 0;
  if (ex && in(tx - 1, ty)) --wx;
  else if (ey && in(tx, ty - 1)) --wy;
  else if (ex && ey && in(tx - 1, ty - 1)) {
    --wx;
    --wy;
  }
}
