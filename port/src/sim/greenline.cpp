// greenLine.pieceMask(piece, out): kGreenPieceMask[piece] as 64 rows of two dwords (low, high); returns 64 (0 past piece 4)
void a_piece_mask(Ctx &c, const uint32_t *a, Ret &r) {
  if (a[0] > 4) {
    r.set_i32(0);
    return;
  }
  for (uint32_t k = 0; k < 64; ++k) {
    const uint64_t v = kGreenPieceMask[a[0]][k];
    c.mem.store<uint32_t>(a[1] + 8 * k, static_cast<uint32_t>(v));
    c.mem.store<uint32_t>(a[1] + 8 * k + 4, static_cast<uint32_t>(v >> 32));
  }
  r.set_i32(64);
}
// greenLine.tileMask(x, y, out): tile (x, y)'s bright texels as tile_mask builds them, 64 rows of two dwords; returns 64
void a_tile_mask(Ctx &c, const uint32_t *a, Ret &r) {
  uint64_t m[64];
  tile_mask(c, static_cast<int32_t>(a[0]), static_cast<int32_t>(a[1]), m);
  for (uint32_t k = 0; k < 64; ++k) {
    c.mem.store<uint32_t>(a[2] + 8 * k, static_cast<uint32_t>(m[k]));
    c.mem.store<uint32_t>(a[2] + 8 * k + 4, static_cast<uint32_t>(m[k] >> 32));
  }
  r.set_i32(64);
}
