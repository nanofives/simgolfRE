uint64_t grid_key(Ctx &ctx) {
  const int32_t n = world_tiles(ctx);
  const int8_t *t = grid_host(ctx, &GameState::g_tileType);
  const uint16_t *f = grid_host(ctx, &GameState::g_tileFlags);
  uint64_t h = 1469598103934665603ull ^ static_cast<uint64_t>(world_n(ctx)) ^ (static_cast<uint64_t>(static_cast<uint8_t>(ctx.gs().g_courseType)) << 40);
  for (int32_t i = 0; i < n; ++i) {   // P39C2_2: every type (the shape's edge kinds read the neighbours' types), not only green or not
    const uint32_t v = static_cast<uint8_t>(t[i]) | ((f[i] & kFlagCup) ? ((1u | ((f[i] & kFlagHole) << 1)) << 8) : 0u);
    h = (h ^ v) * 1099511628211ull;
  }
  return h;
}
