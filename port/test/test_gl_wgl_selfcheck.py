"""The host-OpenGL startup self-check and the default terrain renderer (roadmap S3.20, decision G13; port/include/portsim/sim/gl_wgl.h
wgl_self_check, terrain_live.h LiveTerrain::choose_renderer, port/app/main.cpp --gl).

Decision G13 (final): GlRaster is the default terrain renderer; the host's OpenGL is opt-in. With `--gl auto` (app, framegate) the
host's OpenGL is used after a startup self-check: a reference pass drawn with it, SHA-256 of a 32 x 32 rectangle compared with a pinned
hash of the ORIGINAL's pixels; anything else, or a host without a generic 16-bit pixel format, falls back to GlRaster with the reason
logged. `--gl host` (= wgl) takes the host's OpenGL without the check. The reference (port/src/sim/gl_wgl_ref.inc, generated by
log/roadmap/S3/20_make_ref.py) is the part of the original's recorded pass c7/z2_r1 (port/corpus/gl) that reaches the rectangle.

    ~/bin/py -3.12 -m pytest port/test/test_gl_wgl_selfcheck.py -q      (Windows only; SG_BACKEND=win32 runs it on the Win32 runner;
                                                                         the app tests need SG_APP_EXE + SG_PORTSIM_DLL of one build)
Controls (RED): the pinned hash with one hex digit changed (perturb 1, negctl gfx.family.terrain 13), the reference pass with every
texture coordinate one texel off (perturb 2, negctl 14), a DIB with RGB565 masks (variant 1, negctl 8), the same reference through
GlRaster with roadmap S3.21's rules off (glWgl.rasterCheck(1): the U-1392 residual S3.20 measured, 45 of the 1,024 pixels). Since
S3.21 the default GlRaster passes the check too (0 pixels differ); the app's `--gl auto` runs the check on the host GL only. Blind, recorded: the DIB rows top-down (variant 2) and the texture names
bound unmapped (variant 3), as for the frames (log/roadmap/S3/15_notes.md, U-1811). Fallback: no pixel format (variant 4, negctl 12).
"""
from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

import numpy as np
import pytest

pytestmark = pytest.mark.port

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPO = ROOT if (ROOT / "log" / "roadmap").is_dir() else next(p for p in ROOT.parents if (p / "log" / "roadmap").is_dir())
INSTALL = REPO / "original"
SNAP = REPO / "port" / "corpus" / "gl" / "c7" / "snaps" / "z2_r1"
REF_INC = ROOT / "port" / "src" / "sim" / "gl_wgl_ref.inc"
# the generator: in the repository, or (a mirror tree under port/build) in the repository holding it
GEN = next((p / "log" / "roadmap" / "S3" / "20_make_ref.py" for p in (ROOT, *ROOT.parents)
            if (p / "log" / "roadmap" / "S3" / "20_make_ref.py").exists()), ROOT / "log" / "roadmap" / "S3" / "20_make_ref.py")
RASTER_PX = 45          # pixels of the rectangle GlRaster with S3.21's rules off draws differently from the original (U-1392)


def _ref():
    t = REF_INC.read_text()
    g = lambda k: int(t.split(f"{k} = ")[1].split(",")[0].split(";")[0])  # noqa: E731
    return {"x": g("kRefX"), "y": g("kRefY"), "w": g("kRefW"), "h": g("kRefH"), "sha": t.split('kRefSha256[] = "')[1].split('"')[0]}


def _original_rect():
    r = _ref()
    post = np.frombuffer((SNAP / "dib_post.bin").read_bytes(), dtype="<u2").reshape(600, 800)
    return post[r["y"]:r["y"] + r["h"], r["x"]:r["x"] + r["w"]]


@pytest.fixture(scope="module")
def lib():
    if sys.platform != "win32":
        pytest.skip("the host-OpenGL backend is Windows' generic opengl32")
    if not (INSTALL / "golf_clean.exe").exists():
        pytest.skip("no install (original/)")
    from port.test import lib as L
    return L.load()


def _kv(raw: bytes | None) -> dict:
    t = (raw or b"").decode(errors="replace")
    return dict(ln.split(" ", 1) for ln in t.splitlines() if " " in ln)


def _check(lib, fn="glWgl.selfCheck", args=(0, 0)):
    with lib.state() as st:
        st.files_root(str(INSTALL))
        ret = st.call(fn, list(args)).eax
        raster = fn.endswith("rasterCheck")
        kv = _kv(st.files_read("$wgl/rastercheck.txt" if raster else "$wgl/selfcheck.txt"))
        rect = st.files_read("$wgl/raster_rect.555" if raster else "$wgl/selfcheck_rect.555")
    px = np.frombuffer(rect, dtype="<u2").reshape(32, 32) if rect and len(rect) == 2048 else None
    return ret, kv, px, rect


# ------------------------------------------------------------------------------------------------ the reference
def test_reference_hash_is_the_originals():
    """kRefSha256 is SHA-256 of the original's recorded pixels over the rectangle, and the committed reference is the generator's"""
    if not SNAP.exists():
        pytest.skip("no gl corpus (port/corpus/gl/c7)")
    r = _ref()
    assert hashlib.sha256(_original_rect().astype("<u2").tobytes()).hexdigest() == r["sha"]
    if GEN.exists():
        spec = importlib.util.spec_from_file_location("s3_20_make_ref", GEN)
        m = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(m)
        built = m.build("c7", "z2_r1", (r["x"], r["y"], r["w"], r["h"]))
        assert m.emit(built) == REF_INC.read_text(), "gl_wgl_ref.inc differs from log/roadmap/S3/20_make_ref.py's output"


def test_self_check_passes_on_this_host(lib):
    ret, kv, px, rect = _check(lib)
    assert ret == 1 and kv["pass"] == "1", kv
    assert kv["got"] == kv["want"] == _ref()["sha"]
    assert hashlib.sha256(rect).hexdigest() == kv["got"]          # the port's SHA-256 equals hashlib's
    if SNAP.exists():
        assert int((px != _original_rect()).sum()) == 0


def test_default_rasteriser_passes_the_self_check(lib):
    """roadmap S3.21 (float32 vertex rule and clipping, default on): GlRaster equals the original on the reference rectangle"""
    ret, kv, px, _ = _check(lib, "glWgl.rasterCheck", (0,))
    assert ret == 1 and kv["pass"] == "1" and kv["got"] == kv["want"] == _ref()["sha"], kv
    if SNAP.exists():
        assert int((px != _original_rect()).sum()) == 0


def test_self_check_sees_the_rasteriser_residual(lib):
    """GlRaster with S3.21's rules off on the same reference: RED, on exactly the U-1392 one-level pixels"""
    ret, kv, px, _ = _check(lib, "glWgl.rasterCheck", (1,))
    assert ret == 0 and kv["pass"] == "0" and kv["got"] != kv["want"], kv
    if SNAP.exists():
        orig = _original_rect()
        d = px != orig
        assert int(d.sum()) == RASTER_PX
        rgb = lambda a: np.stack([(a >> 10) & 31, (a >> 5) & 31, a & 31]).astype(int)  # noqa: E731
        assert int(np.abs(rgb(px) - rgb(orig)).max()) == 1


@pytest.mark.parametrize("args,why", [((0, 1), "wrong pinned hash"), ((0, 2), "texture coordinates one texel off"),
                                      ((1, 0), "RGB565 DIB")])
def test_self_check_controls_read_red(lib, args, why):
    ret, kv, _px, _ = _check(lib, args=args)
    assert ret == 0 and kv["pass"] == "0", (why, kv)


@pytest.mark.parametrize("variant", [2, 3])
def test_self_check_blind_variants(lib, variant):
    # recorded as blind (equivalent on the generic implementation): top-down rows, unmapped texture names
    ret, _kv2, _px, _ = _check(lib, args=(variant, 0))
    assert ret == 1


def test_self_check_without_a_pixel_format(lib):
    ret, kv, px, _ = _check(lib, args=(4, 0))
    assert ret == 0 and px is None and kv["reason"].startswith("no host OpenGL"), kv


# ------------------------------------------------------------------------------------------------ LiveTerrain's choice
def _choose(lib, mode: int, negctl: int = 0) -> tuple[int, dict]:
    from port.test import terrainlive as TL
    prev = lib.negctl("gfx.family.terrain", negctl) if negctl else None
    try:
        with lib.state() as st:
            st.files_root(str(INSTALL))
            assert TL.live_attach(lib, st, 0) == 0
            ret = st.call("terrainLive.renderer", [mode]).eax
            kv = _kv(st.files_read("$wgl/renderer.txt"))
            TL.live_detach(lib, st)
    finally:
        if negctl:
            lib.negctl("gfx.family.terrain", prev or 0)
    return ret, kv


def test_auto_picks_the_host_gl(lib):
    ret, kv = _choose(lib, 2)
    assert ret == 1 and kv["backend"] == "wgl" and kv["check"] == "pass" and kv["reason"].startswith("self-check passed"), kv


@pytest.mark.parametrize("negctl,reason", [(13, "self-check failed"), (14, "self-check failed"), (8, "self-check failed"),
                                           (12, "no host OpenGL")])
def test_auto_falls_back_to_the_rasteriser(lib, negctl, reason):
    ret, kv = _choose(lib, 2, negctl)
    assert ret == 0 and kv["backend"] == "raster" and kv["reason"].startswith(reason), kv


def test_explicit_modes(lib):
    ret, kv = _choose(lib, 0)
    assert ret == 0 and kv["backend"] == "raster" and kv["check"] == "none", kv
    ret, kv = _choose(lib, 1)
    assert ret == 1 and kv["backend"] == "wgl" and kv["check"] == "none", kv


def test_framegate_fallback_rows_equal_the_rasteriser(lib):
    """an opt-in `auto` run whose self-check fails (control 13) draws with GlRaster: its rows equal the default (GlRaster) run's,
    renderer column raster with the check's reason; the passing `auto` run is the host GL's (every sandbox_basic row PASS)"""
    from port.test import framegate as FG
    prev = lib.negctl("gfx.family.terrain", 13)
    try:
        fell = FG.run_scenario("sandbox_basic", lib=lib, probe=False, gl="auto")
    finally:
        lib.negctl("gfx.family.terrain", prev or 0)
    raster = FG.run_scenario("sandbox_basic", lib=lib, probe=False)
    auto = FG.run_scenario("sandbox_basic", lib=lib, probe=False, gl="auto")
    key = lambda rows: [(r["checkpoint"], r["status"], r.get("regions")) for r in rows]  # noqa: E731
    assert key(fell) == key(raster)
    assert {r["renderer"] for r in fell} == {"raster"} and all("self-check failed" in r["renderer_reason"] for r in fell)
    assert {r["renderer"] for r in auto} == {"wgl"} and {r["renderer"] for r in raster} == {"raster"}
    assert all(r["status"] == "PASS" for r in auto), [(r["checkpoint"], r["status"]) for r in auto]


# ------------------------------------------------------------------------------------------------ the app's choice and its log line
def _app():
    exe, dll = os.environ.get("SG_APP_EXE"), os.environ.get("SG_PORTSIM_DLL")
    if not exe or not pathlib.Path(exe).exists():
        pytest.skip("SG_APP_EXE (simgolf_port.exe) not set")
    return pathlib.Path(exe)


def _app_run(extra=(), backend_env=None) -> tuple[dict, str]:
    exe = _app()
    tmp = pathlib.Path(tempfile.mkdtemp(prefix="s3_20_app_"))
    env = {k: v for k, v in os.environ.items() if k != "SG_GL_BACKEND"}
    if backend_env:
        env["SG_GL_BACKEND"] = backend_env
    try:
        args = [str(exe), "--install", str(INSTALL), "--data", str(tmp / "data"), "--record-dir", str(tmp / "rec"),
                "--present-trace", str(REPO / "port" / "corpus" / "traces" / "sandbox_basic.trace"), "--no-window",
                "--max-records", "3", *extra]
        r = subprocess.run(args, cwd=str(REPO), capture_output=True, text=True, timeout=600, env=env)
        js = json.loads((tmp / "rec" / "terrain_renderer.json").read_text())
        return js, r.stderr
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def test_app_default_is_glraster():
    """decision G13 (final): without --gl or SG_GL_BACKEND the app draws with GlRaster, and says so"""
    js, err = _app_run()
    assert js["source"] == "default" and js["mode"] == "raster" and js["backend"] == "raster" and not js["checked"], js
    assert "simgolf_port: terrain renderer raster (default raster): GlRaster (the default renderer, decision G13)" in err, err


def test_app_auto_is_the_checked_host_gl():
    js, err = _app_run(["--gl", "auto"])
    assert js["mode"] == "auto" and js["backend"] == "wgl" and js["pass"] and js["got"] == _ref()["sha"], js
    assert "simgolf_port: terrain renderer wgl (--gl auto): self-check passed" in err and "[self-check " in err, err


@pytest.mark.parametrize("mode,reason", [(13, "self-check failed"), (12, "no host OpenGL")])
def test_app_auto_falls_back_with_the_log_line(mode, reason):
    js, err = _app_run(["--gl", "auto", "--negctl", f"reg:gfx.family.terrain={mode}"])
    assert js["backend"] == "raster" and js["reason"].startswith(reason), js
    assert f"simgolf_port: terrain renderer raster (--gl auto): {reason}" in err, err


@pytest.mark.parametrize("value", ["host", "wgl"])
def test_app_host_without_the_check(value):
    js, err = _app_run(["--gl", value])
    assert js["mode"] == "wgl" and js["backend"] == "wgl" and not js["checked"], js
    assert f"terrain renderer wgl (--gl {value}): the host's OpenGL asked for (no self-check)" in err, err


def test_app_environment_override():
    """without --gl, SG_GL_BACKEND chooses (here auto); --gl wins over it"""
    js, err = _app_run(backend_env="auto")
    assert js["source"] == "SG_GL_BACKEND" and js["mode"] == "auto" and js["backend"] == "wgl" and js["pass"], js
    js2, _ = _app_run(["--gl", "raster"], backend_env="auto")
    assert js2["source"] == "--gl" and js2["backend"] == "raster", js2
