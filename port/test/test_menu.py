def run_screen_port(lib, scen, mode=0, func=None):
    """the port's run of a screen scenario; `func` (with `mode`) selects another function's wrong body"""
    import ctypes as C
    import tempfile
    from port.test import emu38b as E
    from port.test import test_browser as TB
    from port.test import test_saveload as TS
    cid, entry, extra, steps = scen
    name = {PICK_A_PRO: "pickAProScreen", START_NEW_COURSE: "startNewCourse"}[entry]
    raws, cursors = TB.flatten(steps)
    words = [len(raws), len(cursors)]
    for c in raws:
        words += [c.handler, c.a0 & 0xFFFFFFFF, c.a1 & 0xFFFFFFFF, c.async_ctrl, c.async_shift, c.t]
    for x, y in cursors:
        words += [x & 0xFFFFFFFF, y & 0xFFFFFFFF]
    script = (C.c_uint32 * len(words))(*words)
    peer_names = [p[1] for p in E.SAVE_PEERS if p[1] != "Window::refreshFull"]
    logbuf = (C.c_uint32 * (1 + 8 * TS.PEER_LOG_CAP))()
    with tempfile.TemporaryDirectory(prefix="sg38j_pro_") as d:
        root = pathlib.Path(d)
        files = E.Files(_screen_files(extra))
        for k, v in files.data.items():
            p = root / files.spell[k]
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_bytes(v)
        if mode:
            lib.negctl(func or name, mode)
        try:
            with lib.state() as st:
                st.set_data_base(DATA_VA)
                st.load_image(_screen_image(lib, cid))
                st.files_root(root)
                st.map(0x30000000, script, readonly=True)
                st.map(TS.PEER_LOG_VA, logbuf)
                for nm in peer_names:
                    st.call("commands.recordPeer", [fnv1a(nm), TS.PEER_LOG_VA, TS.PEER_LOG_CAP])
                st.call("saveload.setScript", [0x30000000])
                try:
                    eax, code = st.call(name, []).eax, 0
                except L.SgError as e:
                    eax, code = None, e.code
                st.call("saveload.clearScript", [])
                st.call("commands.recordClear", [])
                out = st.image()
        finally:
            lib.negctl_reset()
        n = min(logbuf[0], TS.PEER_LOG_CAP)
        calls = [tuple(logbuf[1 + 8 * k:1 + 8 * k + 8]) for k in range(n)]
    return eax, code, out, calls


def compare_screen(lib, scen) -> str:
    r, io = run_screen_original(lib, scen)
    eax, code, out, calls = run_screen_port(lib, scen)
    if r.err.startswith("NeedInput"):
        return "" if code == L.SG_E_NO_RESOURCE else f"the original waits for input, the port code {code}"
    if r.err:
        return f"original: {r.err}"
    if code != 0:
        return f"port code {code}"
    if eax != r.eax:
        return f"eax port {eax} original {r.eax}"
    d = first_diff(lib, out, r.image)
    if d:
        return d
    if calls != io.peer_calls:
        return f"recorded calls differ: port {calls} original {io.peer_calls}"
    return ""


