def fnv1a(s: str) -> int:
    h = 0x811C9DC5
    for c in s.encode():
        h = ((h ^ c) * 0x01000193) & 0xFFFFFFFF
    return h


def objs(lib):
    return {n: (off, sz) for n, off, sz in lib.objects()}


def put(lib, img: bytearray, name: str, data: bytes, at=0):
    off, size = objs(lib)[name]
    assert at + len(data) <= size
    img[off + at:off + at + len(data)] = data


def get(lib, img: bytes, name: str, n=None, at=0) -> bytes:
    off, size = objs(lib)[name]
    return bytes(img[off + at:off + at + (n if n is not None else size)])


def first_diff(lib, a: bytes, b: bytes, mask=()) -> str:
    skip = [objs(lib)[m] for m in mask]
    for i in range(len(a)):
        if a[i] != b[i] and not any(o <= i < o + s for o, s in skip):
            for n, (off, sz) in objs(lib).items():
                if off <= i < off + sz:
                    return f"{n}+{i - off:#x}: port {a[i]:#04x} original {b[i]:#04x}"
            return f"byte {i:#x}"
    return ""


