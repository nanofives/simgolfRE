# freeBlock / freeTable over random pools (the oracle): the regions, the sheet tables after
def pool_image(lib, seed) -> bytes:
    import random
    rng = random.Random(seed)
    img = bytearray((SEG / "cov_b_career_types" / "00" / "start.data.bin").read_bytes())
    starts, lens, at = [], [], 0
    for i in range(100):
        if rng.random() < 0.4:
            starts.append(-1)
            lens.append(0)
        else:
            at += rng.randrange(0, 40)
            n = rng.randrange(1, 30)
            starts.append(at)
            lens.append(n)
            at += n + rng.choice([0, 0, 5])
    rng.shuffle(starts) if seed % 3 == 0 else None
    put(lib, img, "g_cellFreeStart", struct.pack("<100i", *starts))
    put(lib, img, "g_cellFreeLen", struct.pack("<100i", *lens))
    return bytes(img), starts, lens


def free_cases():
    out = []
    for seed in range(1, 9):
        out.append(("freeBlock", seed))
        out.append(("freeTable", seed))
    return out


def _free_args(lib, img, starts, lens, which, seed):
    import random
    rng = random.Random(seed * 7 + 1)
    used = [(s, n) for s, n in zip(starts, lens) if s >= 0]
    if which == "freeBlock":
        s, n = rng.choice(used) if used else (0, 1)
        base = s + n if rng.random() < 0.7 else s + n + 3     # adjacent to a region's end, or not
        return FREE_BLOCK, [base, rng.randrange(1, 20)], img
    sheet = rng.randrange(0x190, 0x23D)
    img = bytearray(img)
    first = rng.choice([-1] + [s + n for s, n in used])
    put(lib, img, "g_sheetFirstCell", struct.pack("<i", first), at=4 * sheet)
    put(lib, img, "g_sheetCols", struct.pack("<i", rng.randrange(0, 8)), at=4 * sheet)
    put(lib, img, "g_sheetRows", struct.pack("<i", rng.randrange(0, 5)), at=4 * sheet)
    return FREE_TABLE, [sheet], bytes(img)


