# ------------------------------------------------------------------------------------------------ digests, controls
def _digest(eax, code, image, calls) -> str:
    h = hashlib.sha256()
    h.update(b"err%d" % code if eax is None else struct.pack("<I", eax & 0xFFFFFFFF))
    h.update(image)
    h.update(repr(calls).encode())
    return h.hexdigest()[:24]


def _digests(lib, mode=0, func_neg=None) -> dict:
    out = {}
    for sc in SCEN:
        eax, code, img, calls = run_port(lib, "loadWorldAssets", [], scen_image(lib, sc), mode, func_neg)
        out["lwa:" + sc[0]] = _digest(eax, code, img, calls)
