// C3 batch c3fh (round 34, 2026-10-13) of sound.dll: path B2 of re/C3_ENDGAME_PLAN.md, the x87-faithful pilot.
// Addresses in SG_HOOK and in the `// 0x...` comment lines are RVAs; instruction addresses quoted inside each body are VAs
// (VA = 0x10000000 + RVA). Hand-written from the disassembly (log/c3/alt/c3fh_dis/sound_<va>.txt, asm2inline.py --list).
//
// THE MIXER LEAVES. Voice_mixSetMono16 0x10019b20 and its five twins hold the whole resampler in x87 registers: after
// `fninit` they load the control word 0x0f7f (`mov dword [ebp-0x24], 0xf7f` at 0x10019ca8, `fninit` 0x10019cbf, `fldcw
// [ebp-0x24]` 0x10019cc1: precision control 11 = 64-bit significand, rounding control 11 = toward zero), push the two
// gains, the step and the position, and keep them on the register stack for the whole loop; nothing is spilled except
// the two output doubles per sample (`fstp qword [edi]` / `[edi+8]`) and the fractional position at the end (`fst qword
// [ebp-0x34]`). They never restore the control word and return with 4 or 5 values still on the register stack.
//
// MSVC has no 80-bit type (`long double` is the 53-bit double, and this file is compiled with SSE2 codegen, which ignores
// the x87 control word), so a body written with double / long double rounds every intermediate to 53 bits. X80 below is
// the register itself: 10 bytes (64-bit significand, 15-bit exponent), loaded and stored with `fld` / `fstp tbyte`, which
// are exact. Every arithmetic step is ONE x87 instruction applied to X80 operands under the control word the original
// loaded, the same operation and operand order the original executes at the address cited next to it, so each result is
// rounded exactly where the original rounds it (to 64 bits, toward zero) and stored to double only where it stores. The
// loop structure (positions, interpolation, gain ramp, loop wrap, end handling, state write-back) is plain C.
// log/c3/c3fh_notes.txt section 2 has the pilot's measurement: the same body with `double` in place of X80 is RED.
//
// Exit state: like the original, a body leaves the x87 control word at 0x0f7f and pushes its live registers back onto the
// register stack in the original's order (bottom first), so the caller (renderChannelSingle 0x10036280 does fld / fsub /
// fcomp right after the call) and the next call see the same unit the original leaves. The ramp division before
// `fninit` runs on the entering stack and control word, as in the original.
