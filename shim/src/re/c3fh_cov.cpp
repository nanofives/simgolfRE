// c3fh: counts only while a fixture has armed the switch (__freeze.negOn(), reset at the key's flush), so the game's own
// calls at boot (gameMain -> allocResampleTable, the sound init) are not counted.
extern "C" __declspec(dllexport) volatile int C3fhCovNegCtl[4] = {0, 0x5147454e, 0, 0};
static inline bool c3fh_br(unsigned id, bool v) {
    if (!C3fhCovNegCtl[0]) return v;
    while (InterlockedExchange(&c3fhcov::g_lock, 1)) Sleep(0);
    // c3fh: the file is rewritten only when a side is hit for the first time (the mixer and table loops evaluate a decision
    // hundreds of thousands of times per key); the side sets in the report are exact, the counts are not kept.
    bool first = c3fhcov::g_counts[id][v ? 0 : 1] == 0;
    c3fhcov::g_counts[id][v ? 0 : 1] = 1;
    if (id >= c3fhcov::g_n) { c3fhcov::g_n = id + 1; first = true; }
    if (first) c3fhcov::Flush();                        // synchronous: the harness kills the game right after the last vector
    InterlockedExchange(&c3fhcov::g_lock, 0);
    return v;
}
