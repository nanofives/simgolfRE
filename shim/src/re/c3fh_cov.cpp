// The per-voice gain step Channel_recomputeVoiceGains, Channel_setRate and Channel_setReverseRate share (Gains's
// addresses; the other two are given at their call sites): with the engine rate R (slot +0x40) and the channel rate r,
// fild qword both (0x1003549f / 0x100354a7), fcom (0x100354ab) and, only when r > R (`test ah, 0x41; jne`, 0x100354b2):
// q = r / R (fdivrp 0x100354b4), the voice's +0 word = __ftol(fild dword [s-0x9c] / q) (0x100354b6-0x100354be) and
// d = [s-0x94] / q (fdivr 0x100354c3); otherwise the word is [s-0x9c] and d = [s-0x94] (0x100354cd-0x100354dd).
// Returns the value stored and leaves d in *out (the caller stores it with fst / fstp).
int voiceGainStep(char* s, unsigned R, unsigned r, X80* out) {
    X80 A, B, q, v;
    ldU32(&A, R);
    ldU32(&B, r);
    if (c3fh_br(63, ((x80Com(&B, &A) >> 8) & 0x41))) {
        ld64(out, s - 0x94);
        return fat<int>(s, -0x9c);
    }
    x80Div(&q, &B, &A);
    ldI32(&v, fat<int>(s, -0x9c));
    x80Div(&v, &v, &q);
    int w = ftolLow(&v);
    X80 d;
    ld64(&d, s - 0x94);
    x80Div(out, &d, &q);
    return w;
}

