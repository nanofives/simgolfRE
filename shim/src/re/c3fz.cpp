// BR(jcc, cond) names the original's conditional jump a condition stands for; HIT(a) marks a jump-table target. In the
// coverage build (shim/src/re/c3fz_cov.cpp, generated by log/c3/alt/c3fz_cov_gen.py with C3FZ_COV defined, never listed in
// shim/re_batches.txt) they also count the outcomes per address in the exported C3fzCovTable (entries {addr, true count,
// false count}); log/c3/alt/c3fz_cov.py reads it. In every other build BR(a, c) is c and HIT(a) is nothing.
#ifdef C3FZ_COV
extern "C" __declspec(dllexport) volatile unsigned C3fzCovTable[3 * 256] = {0};
static bool C3fzBr(unsigned addr, bool c) {
    for (int i = 0; i < 256; ++i) {
        volatile unsigned* e = &C3fzCovTable[3 * i];
        if (e[0] == 0) e[0] = addr;
        if (e[0] == addr) { ++e[c ? 1 : 2]; break; }
    }
    return c;
}
#define BR(a, c) C3fzBr((a), (c) ? true : false)
#define HIT(a) C3fzBr((a), true)
#else
#define BR(a, c) (c)
#define HIT(a) ((void)0)
#endif

