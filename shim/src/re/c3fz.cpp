namespace {

inline void Redraw(void* self) { vslot<Vfn0_t>(self, 0x120)(self, 0); }   // `call [edx+0x120]`, ecx = this
inline void Beep() { (*reinterpret_cast<MessageBeep_t*>(kIatMessageBeep))(0); }   // push 0; call [0x4ba1bc]

int UpDown(void* self, bool down) {
    int lines[32];                                                          // [esp+0x18], 0x80 bytes
    int count;                                                              // [esp+0xc]
    int outX, outY;                                                         // [esp+0x14], [esp+0x10]
    kWrapToLines(self, 0, lines, &count);                                   // 0x004867eb / 0x00486841
    int caret = I(self, 0x5a4);                                             // 0x004867f0 / 0x00486846
    kCharPosToPixel(self, 0, lines, count, caret, &outX, &outY);            // 0x0048680d / 0x00486863
    int h = kWidgetValue(B(self) + 0x274, 0);                               // 0x00486822 / 0x00486878
    int y = down ? Add32(outY, h) : Sub32(outY, h);                         // 0x00486885 / 0x0048682b
    int p = kPixelToCharPos(self, 0, outX, y, lines, count);                // 0x0048688b
    if (BR(0x00486896, p != I(self, 0x5a4))) {                              // 0x00486890 / 0x00486896
        I(self, 0x5a4) = p;                                                 // 0x004869a6
    } else {
        Beep();                                                             // 0x0048689e
    }
    Redraw(self);                                                           // 0x004868a8 / 0x004869ac
    return 1;                                                               // 0x004868b0 / 0x004869b4
}
}  // namespace

