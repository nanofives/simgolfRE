// __cdecl, no arguments, `ret` (0x004593e8 returns 1, 0x004593f5 returns 0). Frame: `sub esp, 0xf0` then four pushes;
// offsets below are relative to esp after the pushes (L<off>), as the listing reads them where no argument is pushed.
//
// The nine lots are a 3 x 3 grid of 16 x 16 tile blocks of the 50 x 50 tile map 0x005722e8 (signed bytes, index
// row * 50 + col, 0x14 = a tile that is for sale): lot n covers rows (n % 3) * 16 + 1 .. + 16 and columns (n / 3) * 16 + 1
// .. + 16 (0x00458bae..0x00458c19). The byte map 0x00542414 (same index) holds, per tile, the type the tile becomes when
// bought; it also names the lot's three most common types in the lot's text.
//
// The frame slots from L58 to Ldc are one run of dwords the code indexes with a computed index (`[esp + eax*4 + 0x5c]`
// 0x004592f0 with eax = -1 reads L58; `[esp + edx*4 + 0x84]` 0x00458c58 with a negative type byte writes below L80), so the
// reimplementation keeps them as one array F: F[0] = L58 (the last lot's n % 3), F[1..9] = L5c cost[9] (written on the
// first pass only, 0x00458db0), F[10..32] = L80 counts[23] (per type byte, zeroed per lot by `rep stosd` 0x00458c22),
// F[33..41] = Ldc (the lot number, written at 0x00458db8 and never read).
//
// Uninitialised reads of the original: the label position L2c / L24 is written in the tile scan only for the lot's
// centre tile (i = 8, j = 8, 0x00458cbc..0x00458cd1) and after each lot (0x00458d8b / 0x00458d9b, 0x00459088); lot 0 of
// the first pass reads it before any write when it has a tile for sale but its centre tile is not (0x00458d39 /
// 0x00458d46). The fixtures never build that case; the reimplementation starts the pair at 0.
