// the region under the cursor (0x004591f1..0x00459273): lots 0..8 (columns x < 0x106, 0x110 <= x < 0x20c, x >= 0x21a,
// bands of 68 rows from y = 0x36), -2 the done button, -1 nothing
static int BuyHit(int x, int y) {
    if (!BR(0x004591f6, x < 0xf) && !BR(0x004591fe, x >= 0x307) && !BR(0x00459203, y < 0x36) &&
        !BR(0x0045920a, y >= 0x102)) {
        const int band = (y - 0x36) / 68;                                          // 0x0045920c..0x0045921e
        if (!BR(0x00459226, x >= 0x106)) return band;                              // 0x00459228
        if (!BR(0x00459232, x < 0x21a)) return band + 6;                           // 0x00459234
        if (!BR(0x0045923f, x < 0x110) && !BR(0x00459247, x >= 0x20c)) return band + (NEG(1) ? 0 : 3); /* negctl 1: showBuyLandScreen: the middle column hit-tests as the first column */   // 0x00459249
        return -1;                                                                 // 0x00459273
    }
    if (!BR(0x00459254, x < 0x296) && !BR(0x0045925c, x >= 0x2d6) && !BR(0x00459263, y < 0x215) &&
        !BR(0x0045926a, y >= 0x255)) return -2;                                    // 0x0045926c
    return -1;                                                                     // 0x00459273
}

