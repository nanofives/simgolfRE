// Fixtures: re/frida/js/fixtures.d/c3fs.js. Registry: re/frida/registry.d/c3fs.py.
// Purposes and per-jcc tables: log/c3/c3fs_purpose.md. Notes and drops: log/c3/c3fs_notes.txt.
//
// Every body is hand-written from the disassembly (log/c3/alt/c3fs_asm/<addr>_<name>.asm, written by
// log/c3/alt/c3fs_dis.py) and cites the instruction each fact comes from. __thiscall is emulated with __fastcall
// (ecx = this, edx unused); callees run through their original addresses, so a hooked callee uses its own
// reimplementation during the A/B.
//
// Frames. Each function here reads at least one stack slot before any instruction writes it, so its value is whatever
// the stack held. To make that value the same in both arms of an A/B, each body is entered through a naked thunk that
// builds the original's frame at the same address (the same `sub esp` and register pushes) and passes its base F (esp
// after the pushes) to the body, which keeps every local at the original's offset from F. Below F the thunk leaves a
// 0x1000-byte gap before the body's own frame, so a callee that the original calls first, before the slot is read, can
// be called with esp exactly where the original has it (CallOnFrame below): a fixture stand-in for that callee then
// seeds the slot through its own esp in both arms alike.
