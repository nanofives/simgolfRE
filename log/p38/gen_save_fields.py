"""38b: generate port/src/sim/saveload_fields.inc, the byte-range tables of serializeCourse (0x0040afa0, the .sve body in
save / load order) and deserializeCourse (0x0040bbf0, the course file body), as (GameState member, offset, size) rows.

Specification: the C3 hook sources shim/src/re/c3fb.cpp (kFields, A/B GREEN against the original) and c3fa.cpp
(kCourseFields), resolved to GameState members with re/model/addresses.tsv. Cross-checked against re/model/sve_fields.tsv
(the G2 table: 116 saves round-trip byte-identical through it).

    ~/bin/py -3.12 log/p38/gen_save_fields.py
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SHIM = ROOT / "shim" / "src" / "re"
OUT = ROOT / "port" / "src" / "sim" / "saveload_fields.inc"


def table(text: str, start_pat: str):
    i = text.index(start_pat)
    j = text.index("};", i)
    return [(int(a, 16), int(b, 0)) for a, b in re.findall(r"\{\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\}", text[i:j])]


def main():
    objs = []
    for r in csv.DictReader(open(ROOT / "re" / "model" / "addresses.tsv"), delimiter="\t"):
        if r["module"] == "golf_clean.exe":
            objs.append((int(r["va"], 16), int(r["size"], 16), r["symbol"]))
    objs.sort()

    def resolve(va):
        for b, s, n in objs:
            if b <= va < b + s:
                return n, va - b
        raise SystemExit(f"no object holds {va:#x}")

    ser = table((SHIM / "c3fb.cpp").read_text(), "const Field kFields[] = {")
    # c3fb's rows are `{0x..., 0x...},     // call ...`: the generic pattern above takes "0x.., 0x.." pairs
    des = table((SHIM / "c3fa.cpp").read_text(), "kCourseFields[][2] = {")
    tails = {"ser_flag30": (0x004E06C8, 0x8C0), "ser_flag21_a": (0x0058F338, 0xB7C0), "ser_flag21_b": (0x00520A28, 0x19A28)}
    sve = {}
    for r in csv.DictReader(open(ROOT / "re" / "model" / "sve_fields.tsv"), delimiter="\t"):
        sve[r["index"]] = (int(r["va"], 16), int(r["size"], 16), r["model_symbols"])
    body = [sve[k] for k in sve if k.isdigit()]
    mism = [(i, a, b) for i, (a, b) in enumerate(zip(ser, [(v, s) for v, s, _ in body])) if a != b]
    print(f"serialize rows {len(ser)}, sve_fields body rows {len(body)}, mismatches {len(mism)}", file=sys.stderr)

    def rows(lst, label):
        out = []
        for i, (va, size) in enumerate(lst):
            n, d = resolve(va)
            out.append(f"    {{offsetof(GameState, {n}) + {d:#x}u, {size:#x}u}},  // {label} {i}: {n}+{d:#x}")
        return out

    lines = ["// GENERATED by log/p38/gen_save_fields.py (do not edit): the .sve body fields of serializeCourse and the course",
             "// file fields of deserializeCourse as (offset into GameState, byte count), from the C3 hook sources' tables",
             "// (shim/src/re/c3fb.cpp, c3fa.cpp) resolved through re/model/addresses.tsv.",
             "static const SaveField kSerializeFields[] = {"] + rows(ser, "ser") + ["};",
             "static const SaveField kDeserializeFields[] = {"] + rows(des, "des") + ["};"]
    for k, (va, size) in tails.items():
        n, d = resolve(va)
        lines.append(f"static const SaveField k_{k} = {{offsetof(GameState, {n}) + {d:#x}u, {size:#x}u}};  // {n}+{d:#x}")
    # the flag word's position in the serialize table (the tail tests read it after the loop)
    fl = [i for i, (va, size) in enumerate(ser) if va == 0x0059E7B8]
    lines.append(f"static const int kSerializeFlagsIndex = {fl[0]};")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({len(ser)} + {len(des)} rows)", file=sys.stderr)
    # the generic offsets of the original image, for the tests (not committed into port code): va -> offset
    return 0


main()
