"""Generate log/roadmap/P1/edits.py from the mirror port/build/P1 against `git archive HEAD` (originals via git show).

Each edit is (path, anchor, replacement): a run of changed lines widened by context lines until the anchor occurs exactly once
in the original file.  ~/bin/py -3.12 log/roadmap/P1/make_edits.py
"""
import difflib, io, pathlib, subprocess, tarfile

ROOT = pathlib.Path(__file__).resolve().parents[3]
MIRROR = ROOT / "port" / "build" / "P1"
FILES = [l.strip() for l in (ROOT / "log/roadmap/P1/files.txt").read_text().splitlines()
         if l.strip() and not l.startswith("log/")]


def original(path):
    """the file as `git archive HEAD` writes it (export eol conversion included, unlike git show)"""
    tar = subprocess.run(["git", "archive", "--format=tar", "HEAD", path], cwd=ROOT, capture_output=True, check=True).stdout
    with tarfile.open(fileobj=io.BytesIO(tar)) as t:
        return t.extractfile(path).read().decode("utf-8")


def hunks(path):
    a = original(path)
    b = (MIRROR / path).read_bytes().decode("utf-8")
    al, bl = a.splitlines(keepends=True), b.splitlines(keepends=True)
    out = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(None, al, bl, autojunk=False).get_opcodes():
        if tag == "equal":
            continue
        lo, hi = i1, i2
        while True:
            anchor = "".join(al[lo:hi])
            if anchor and a.count(anchor) == 1:
                break
            lo, hi = max(0, lo - 1), min(len(al), hi + 1)
        new = "".join(al[lo:i1]) + "".join(bl[j1:j2]) + "".join(al[i2:hi])
        out.append((path, anchor, new))
    return out


edits = [e for p in FILES for e in hunks(p)]
src = ['"""P1 anchored edits (generated by make_edits.py): apply to a clean `git archive HEAD` tree.',
       '', '    ~/bin/py -3.12 log/roadmap/P1/edits.py <tree root>', '"""', 'import pathlib, sys', '',
       f'EDITS = {edits!r}', '', '',
       'def main(root):',
       '    root = pathlib.Path(root)',
       '    for path, anchor, new in EDITS:',
       '        p = root / path',
       '        t = p.read_bytes().decode("utf-8")',
       '        n = t.count(anchor)',
       '        assert n == 1, f"{path}: anchor found {n} times: {anchor[:80]!r}"',
       '        p.write_bytes(t.replace(anchor, new).encode("utf-8"))',
       '    print(f"applied {len(EDITS)} edits")', '', '',
       'if __name__ == "__main__":', '    main(sys.argv[1] if len(sys.argv) > 1 else ".")', '']
(ROOT / "log/roadmap/P1/edits.py").write_text("\n".join(src), encoding="utf-8", newline="\n")
print(f"{len(edits)} edits in {len(FILES)} files")
