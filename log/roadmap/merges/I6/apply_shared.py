def fenced_all(md: str, heading: str, stop: str) -> list:
    i = md.index(heading)
    j = md.index(stop, i + 1)
    return re.findall(r"```[a-z]*\n(.*?)\n```", md[i:j], re.S)


def esc(cell: str) -> str:
    return re.sub(r"(?<!\\)\|", r"\\|", cell)


def md_row(cells: list) -> str:
    assert len(cells) == 6, cells
    return "| " + " | ".join(esc(c.strip()) for c in cells) + " |"


def rows_from_md(lines: list) -> list:
    out = []
    for l in lines:
        body = l.strip()
        assert body.startswith("| ") and body.endswith(" |"), l[:60]
        cells = body[2:-2].split(" | ")
        out.append(md_row(cells))
    return out


def rows_from_tsv(p: pathlib.Path) -> list:
    out = []
    for l in p.read_text(encoding="utf-8").splitlines():
        if not l.strip() or l.startswith("id\t"):
            continue
        c = l.split("\t")
        assert len(c) == 6, (p, l[:60])
        out.append(md_row(c))
    return out


def resolve(text: str, status: str = "resolved"):
    def f(row: str) -> str:
        cells = row.split(" | ")
        assert len(cells) == 6, len(cells)
        if text:
            cells[3] = cells[3].rstrip() + " " + esc(text)
        cells[5] = status + " |"
        return " | ".join(cells)
    return f


def claude_before(R, anchor: str, block: str, what: str):
    rel = "CLAUDE.md"
    t = R.get(rel)
    b = R.conv(rel, block)
    if b.split(R.nl(rel))[0] in t:
        raise SystemExit(f"{what}: already in CLAUDE.md")
    a = R.conv(rel, anchor)
    assert t.count(a) == 1, (what, t.count(a))
    i = t.index(a)
    R.put(rel, t[:i] + b + R.nl(rel) + t[i:])
    print("claude", what)


def section(md: str, heading: str) -> str:
    i = md.index(heading) + len(heading)
    j = md.find("\n## ", i)
    return md[i:j if j > 0 else len(md)].strip("\n")


