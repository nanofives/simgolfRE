import importlib.util
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("s3_13_make_edits", HERE / "13_make_edits.py")
M = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M)

M.BASE = M.ROOT / "port" / "build" / "S3_14_base"
M.MIRROR = M.ROOT / "port" / "build" / "S3_14"
M.OUT = HERE / "14_edits.py"
M.FILES = [
    "port/src/sim/tick.cpp",
    "port/app/tools/app_drive.py",
    "port/test/app_replay.py",
    "port/test/test_app_live.py",
]

if __name__ == "__main__":
    M.main()
    t = M.OUT.read_text(encoding="utf-8")
    head = t[:t.index("EDITS = ")]
    M.OUT.write_text('"""S3.14 edits (generated by log/roadmap/S3/14_make_edits.py from port/build/S3_14_base -> port/build/S3_14; '
                     'applied by\n14_assemble.py after 13_assemble.py\'s steps). (path, old, new): each old text exactly once."""\n'
                     + t[len(head):], encoding="utf-8")
