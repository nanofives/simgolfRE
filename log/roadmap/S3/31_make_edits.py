"""S3.31: turn the tree port/build/S3_31 into anchored edits (31_edits.py) against the plain base port/build/I22 (w10_base.py:
I22's port tree, read only).

    ~/bin/py -3.12 log/roadmap/S3/31_make_edits.py            # writes 31_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "I22"
MIRROR = ROOT / "port" / "build" / "S3_31"
FILES = ["port/src/sim/terrain_overlay.cpp", "port/include/portsim/sim/terrain_overlay.h", "port/test/test_terrain_overlay.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def text(p):
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel in FILES:
        a = text(BASE / rel).splitlines(keepends=True)
        b = text(MIRROR / rel).splitlines(keepends=True)
        file_edits = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = text(BASE / rel)
        for _rel, old, new in file_edits:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == text(MIRROR / rel), rel
        edits += file_edits
    body = ('"""S3.31 edits (generated by log/roadmap/S3/31_make_edits.py; applied by 31_assemble.py): the overlay line\'s float32\n'
            'vertex stage, line rule 8 (terrain_overlay.cpp / .h), and its tests. EDITS: (path, old, new), each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = {}\n")
    (HERE / "31_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits")


if __name__ == "__main__":
    main()
