"""S3.23 (W8.1): turn the shared tree's port/test/framegate.py (the split verdict) into anchored edits against f2dff003 (23_edits.py),
and the new test file into NEW_FILES.

    ~/bin/py -3.12 log/roadmap/S3/23_make_edits.py            # writes 23_edits.py
"""
import importlib.util
import pathlib
import pprint
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
REL = "port/test/framegate.py"
NEW = "port/test/test_framegate_split.py"

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def text(b):
    return b.decode("utf-8").replace("\r\n", "\n")


def main():
    base = text(subprocess.run(["git", "show", f"f2dff003:{REL}"], cwd=ROOT, check=True, capture_output=True).stdout)
    mirror = text((ROOT / REL).read_bytes())
    a, b = base.splitlines(keepends=True), mirror.splitlines(keepends=True)
    edits = [(REL, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
    t = base
    for rel, old, new in edits:
        assert t.count(old) == 1, old[:80]
        t = t.replace(old, new)
    assert t == mirror
    new_files = {NEW: text((ROOT / NEW).read_bytes())}
    body = ('"""S3.23 edits (generated by log/roadmap/S3/23_make_edits.py; applied by 23_assemble.py): framegate --split (the split\n'
            'verdict) and its test. EDITS: (path, old, new), each old text exactly once; NEW_FILES: path -> whole text."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new_files, width=130) + "\n")
    (HERE / "23_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits")


if __name__ == "__main__":
    main()
