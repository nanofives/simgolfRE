"""S3.17: turn the edits made in the mirror port/build/S3_17 into anchored exact-text edits (17_edits.py), the 13_make_edits.py way.

The base of each file is its copy in log/roadmap/S3/17_base/ (taken from port/build/S3_17 before any S3.17 edit; every one equal to
port/build/I15's file = git archive ee6efc1d + 12_assemble.py). For each file in FILES the line diff base -> mirror is cut into hunks;
each hunk's old text is grown by context lines until it occurs exactly once in the base file, and overlapping hunks are merged. The
result is checked by applying every edit to the base text and comparing with the mirror. New files are in 17_files.txt (copied whole).

    ~/bin/py -3.12 log/roadmap/S3/17_make_edits.py            # writes log/roadmap/S3/17_edits.py
"""
import difflib
import pathlib
import pprint

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BASE = HERE / "17_base"
MIRROR = ROOT / "port" / "build" / "S3_17"
I15 = ROOT / "port" / "build" / "I15"
OUT = HERE / "17_edits.py"
FILES = [
    "port/src/sim/routing.cpp",
    "port/src/sim/gfx_surface.cpp",
    "port/src/sim/tick.cpp",
    "port/test/test_gfx_routing.py",
]


def hunks(a, b):
    """[(i1, i2, j1, j2)] line ranges that differ, grown to unique anchors and merged"""
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    raw = [(i1, i2, j1, j2) for tag, i1, i2, j1, j2 in sm.get_opcodes() if tag != "equal"]
    text = "".join(a)
    out = []
    for i1, i2, j1, j2 in raw:
        lo, hi, jlo, jhi = i1, i2, j1, j2
        while True:
            old = "".join(a[lo:hi])
            if old and text.count(old) == 1:
                break
            if lo > 0:
                lo, jlo = lo - 1, jlo - 1
            if hi < len(a):
                hi, jhi = hi + 1, jhi + 1
        if out and lo <= out[-1][1]:
            plo, phi, pjlo, pjhi = out[-1]
            out[-1] = (plo, max(phi, hi), pjlo, max(pjhi, jhi))
        else:
            out.append((lo, hi, jlo, jhi))
    return out


def main():
    for rel in FILES:   # the base is I15's tree
        if (I15 / rel).exists():
            assert (BASE / rel).read_bytes() == (I15 / rel).read_bytes(), f"{rel}: 17_base differs from port/build/I15"
    edits = []
    for rel in FILES:
        a = (BASE / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        b = (MIRROR / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        for lo, hi, jlo, jhi in hunks(a, b):
            edits.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    for rel in FILES:
        t = (BASE / rel).read_text(encoding="utf-8")
        for r, old, new in edits:
            if r != rel:
                continue
            assert t.count(old) == 1, (rel, old[:80])
            assert new not in t or new == old, (rel, "applied twice", new[:80])
            t = t.replace(old, new)
        assert t == (MIRROR / rel).read_text(encoding="utf-8"), rel
    body = ('"""S3.17 edits (generated by log/roadmap/S3/17_make_edits.py from log/roadmap/S3/17_base (= port/build/I15) -> port/build/\n'
            'S3_17; to apply after 12_assemble.py\'s steps). (path, old, new): each old text exactly once. New files: 17_files.txt."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8")
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")
    print("edits", len(edits), "->", OUT)


if __name__ == "__main__":
    main()
