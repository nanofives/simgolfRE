"""S3.16: turn the fixes made in the mirror port/build/S3_16 into anchored exact-text edits (16_edits.py).

The base is port/build/S3_16_base (= 12_assemble.py --dst S3_16_base --commit ee6efc1d, the tree integrator I15 gates; the mirror
S3_16 is the same assembly plus S3.16's fixes). For each file in FILES the line diff base ->
mirror is cut into hunks; each hunk's old text is grown by context lines until it occurs exactly once in the base file, and
overlapping hunks are merged. The result is checked by applying every edit to the base text and comparing with the mirror.

    ~/bin/py -3.12 log/roadmap/S3/16_make_edits.py            # writes log/roadmap/S3/16_edits.py
"""
import difflib
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
BASE = ROOT / "port" / "build" / "S3_16_base"
MIRROR = ROOT / "port" / "build" / "S3_16"
OUT = ROOT / "log" / "roadmap" / "S3" / "16_edits.py"
SNAP_OUT = ROOT / "log" / "roadmap" / "S3" / "16_snapshot_edits.py"
SNAPSHOT_FILES = {"port/test/gfx.py", "port/test/framegate.py"}
# files S3.16 adds (not in the base): copied whole into log/roadmap/S3/16_new/<path>, which 16_assemble.py copies into a tree
NEW_FILES = ["port/test/test_gfx_info_panel.py"]
NEW_DIR = ROOT / "log" / "roadmap" / "S3" / "16_new"
FILES = [
    "port/src/sim/tick_leaves.inc",
    "port/src/sim/shots.cpp",
    "port/src/sim/dialogs.cpp",
    "port/src/sim/tick_ball.inc",
    "port/src/sim/commands_panels.inc",
    "port/test/gfx.py",
    "port/test/framegate.py",
]


def hunks(a, b):
    """[(i1, i2, j1, j2)] line ranges that differ, grown to unique anchors and merged"""
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    raw = [(i1, i2, j1, j2) for tag, i1, i2, j1, j2 in sm.get_opcodes() if tag != "equal"]
    text = "".join(a)
    out = []
    for i1, i2, j1, j2 in raw:
        lo, hi, jlo, jhi = i1, i2, j1, j2
        while True:
            old = "".join(a[lo:hi])
            if old and text.count(old) == 1:
                break
            # grow one line each side (the context is equal in both files)
            if lo > 0:
                lo, jlo = lo - 1, jlo - 1
            if hi < len(a):
                hi, jhi = hi + 1, jhi + 1
        if out and lo <= out[-1][1]:   # overlaps the previous hunk: merge
            plo, phi, pjlo, pjhi = out[-1]
            out[-1] = (plo, max(phi, hi), pjlo, max(pjhi, jhi))
        else:
            out.append((lo, hi, jlo, jhi))
    return out


def main():
    import shutil
    for rel in NEW_FILES:
        assert not (BASE / rel).exists(), rel
        (NEW_DIR / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(MIRROR / rel, NEW_DIR / rel)
    edits = []
    for rel in FILES:
        a = (BASE / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        b = (MIRROR / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        for lo, hi, jlo, jhi in hunks(a, b):
            edits.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    # check: applying every edit (each old text exactly once, in order) to the base gives the mirror
    for rel in FILES:
        t = (BASE / rel).read_text(encoding="utf-8")
        for r, old, new in edits:
            if r != rel:
                continue
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == (MIRROR / rel).read_text(encoding="utf-8"), rel
    # the gate harness's checkpoint position (port/test/gfx.py, port/test/framegate.py) goes to a file of its own (the lead's
    # MERGE_w7 section with S3.15's framegate option); the drawing edits stay in 16_edits.py
    snap = [e for e in edits if e[0] in SNAPSHOT_FILES]
    draw = [e for e in edits if e[0] not in SNAPSHOT_FILES]
    for out, lst, what in ((OUT, draw, "drawing"), (SNAP_OUT, snap, "snapshot-position (gate harness)")):
        body = (f'"""S3.16 {what} edits (generated by log/roadmap/S3/16_make_edits.py from port/build/S3_16_base -> port/build/S3_16;\n'
                'applied on the wave 6 tree (12_assemble.py, ee6efc1d) by 16_assemble.py). (path, old, new): each old text exactly once."""\n'
                "EDITS = " + pprint.pformat(lst, width=130) + "\n")
        out.write_text(body, encoding="utf-8")
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")
    print("edits", len(draw), "->", OUT, "|", len(snap), "->", SNAP_OUT)


if __name__ == "__main__":
    main()
