"""S3.24: turn the mirror port/build/S3_24 into anchored edits (24_edits.py) against the plain f2dff003 files kept in
port/build/S3_24_base_src/ (terrain_overlay.cpp, terrain_overlay.h, test_terrain_overlay.py).

    ~/bin/py -3.12 log/roadmap/S3/24_make_edits.py            # writes 24_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_24_base_src"
MIRROR = ROOT / "port" / "build" / "S3_24"
FILES = {"port/src/sim/terrain_overlay.cpp": "terrain_overlay.cpp", "port/include/portsim/sim/terrain_overlay.h": "terrain_overlay.h",
         "port/test/test_terrain_overlay.py": "test_terrain_overlay.py"}

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def text(p):
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel, base in FILES.items():
        a = text(BASE / base).splitlines(keepends=True)
        b = text(MIRROR / rel).splitlines(keepends=True)
        file_edits = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = text(BASE / base)
        for _rel, old, new in file_edits:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == text(MIRROR / rel), rel
        edits += file_edits
    body = ('"""S3.24 edits (generated by log/roadmap/S3/24_make_edits.py; applied by 24_assemble.py): the overlay line\'s span rule\n'
            '(terrain_overlay.cpp / .h) and its tests. EDITS: (path, old, new), each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = {}\n")
    (HERE / "24_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits")


if __name__ == "__main__":
    main()
