"""S3.13: turn the fixes made in the mirror port/build/S3_13 into anchored exact-text edits (13_edits.py).

The base is port/build/I9 (= 11_assemble.py --commit 78ffb06d, checked equal to a fresh S3_13 assembly before any fix: no file of
port/src, port/include, port/test, re/port, UNCERTAINTIES.md, CLAUDE.md differs). For each file in FILES the line diff base ->
mirror is cut into hunks; each hunk's old text is grown by context lines until it occurs exactly once in the base file, and
overlapping hunks are merged. The result is checked by applying every edit to the base text and comparing with the mirror.

    ~/bin/py -3.12 log/roadmap/S3/13_make_edits.py            # writes log/roadmap/S3/13_edits.py
"""
import difflib
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
BASE = ROOT / "port" / "build" / "I9"
MIRROR = ROOT / "port" / "build" / "S3_13"
OUT = ROOT / "log" / "roadmap" / "S3" / "13_edits.py"
FILES = [
    "port/src/sim/gfx_text.cpp",
    "port/src/sim/gfx_simfoto.cpp",
    "port/src/sim/gfx_results.cpp",
    "port/src/sim/gfx.cpp",
    "port/src/sim/commands.cpp",
    "port/src/sim/commands_layout.inc",
    "port/src/sim/dialogs.cpp",
    "port/test/test_gfx_dialogs2.py",
    "port/test/integrator.py",
]


def hunks(a, b):
    """[(i1, i2, j1, j2)] line ranges that differ, grown to unique anchors and merged"""
    sm = difflib.SequenceMatcher(None, a, b, autojunk=False)
    raw = [(i1, i2, j1, j2) for tag, i1, i2, j1, j2 in sm.get_opcodes() if tag != "equal"]
    text = "".join(a)
    out = []
    for i1, i2, j1, j2 in raw:
        lo, hi, jlo, jhi = i1, i2, j1, j2
        while True:
            old = "".join(a[lo:hi])
            if old and text.count(old) == 1:
                break
            # grow one line each side (the context is equal in both files)
            if lo > 0:
                lo, jlo = lo - 1, jlo - 1
            if hi < len(a):
                hi, jhi = hi + 1, jhi + 1
        if out and lo <= out[-1][1]:   # overlaps the previous hunk: merge
            plo, phi, pjlo, pjhi = out[-1]
            out[-1] = (plo, max(phi, hi), pjlo, max(pjhi, jhi))
        else:
            out.append((lo, hi, jlo, jhi))
    return out


def main():
    edits = []
    for rel in FILES:
        a = (BASE / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        b = (MIRROR / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        for lo, hi, jlo, jhi in hunks(a, b):
            edits.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    # check: applying every edit (each old text exactly once, in order) to the base gives the mirror
    for rel in FILES:
        t = (BASE / rel).read_text(encoding="utf-8")
        for r, old, new in edits:
            if r != rel:
                continue
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == (MIRROR / rel).read_text(encoding="utf-8"), rel
    body = ('"""S3.13 edits (generated by log/roadmap/S3/13_make_edits.py from port/build/I9 -> port/build/S3_13; applied by\n'
            '13_assemble.py after 11_assemble.py\'s steps). (path, old, new): each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8")
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")
    print("edits", len(edits), "->", OUT)


if __name__ == "__main__":
    main()
