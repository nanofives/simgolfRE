"""S3.26: turn the fixes made in the tree port/build/S3_26 into anchored exact-text edits (26_edits.py).

Base of each file: its text at f2dff003 (`git show f2dff003:<path>`) with 22_edits.py applied (22's edits touch only
port/src/sim/gfx_chareditor.cpp, which S3.26 does not change). New files are carried whole in NEW_FILES. Hunks are grown by
13_make_edits.py's rule until each old text occurs exactly once in the base; the result is checked by applying every edit to the
base text and comparing with the tree.

    ~/bin/py -3.12 log/roadmap/S3/26_make_edits.py            # writes log/roadmap/S3/26_edits.py
"""
import importlib.util
import pathlib
import pprint
import subprocess

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
TREE = ROOT / "port" / "build" / "S3_26"
COMMIT = "f2dff003"
FILES = [
    "port/src/sim/gfx_pixel.cpp",
    "port/src/sim/gfx.cpp",
    "port/src/sim/commands_screens.inc",
    "port/test/framegate.py",
    "port/test/test_gfx.py",
    "port/test/test_framegate.py",
    "port/test/gfx.py",
    "port/test/test_app_ingame.py",
    "port/src/sim/tick.cpp",
    "port/src/sim/tick_frame.inc",
]
NEW = ["port/test/test_gfx_s3_26.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def norm(b: bytes) -> str:
    return b.decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel in FILES:
        base = norm(subprocess.run(["git", "show", f"{COMMIT}:{rel}"], cwd=ROOT, capture_output=True, check=True).stdout)
        mine = norm((TREE / rel).read_bytes())
        a, b = base.splitlines(keepends=True), mine.splitlines(keepends=True)
        fe = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = base
        for _r, old, new in fe:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == mine, rel
        edits += fe
    new_files = {rel: norm((TREE / rel).read_bytes()) for rel in NEW}
    body = ('"""S3.26 edits (generated by log/roadmap/S3/26_make_edits.py; applied by 26_assemble.py after 22_assemble.py):\n'
            "the 2D residue fixes of groups 7, 6, 4 and 3 (log/roadmap/S3/26_notes.md). EDITS: (path, old, new), each old text exactly once.\"\"\"\n"
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new_files, width=130) + "\n")
    (HERE / "26_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits in", len(FILES), "files,", len(new_files), "new files")


if __name__ == "__main__":
    main()
