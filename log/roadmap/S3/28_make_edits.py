"""S3.28: turn the changes made in the tree port/build/S3_28 into anchored exact-text edits (28_edits.py).

Base of each file: the plain wave 8 stack, port/build/S3_28_base (`w8_assemble.py --dst S3_28_base --commit 2291a342`). New files are
carried whole in NEW_FILES. Hunks are grown by 13_make_edits.py's rule until each old text occurs exactly once in the base; the result
is checked by applying every edit to the base text and comparing with the tree.

    ~/bin/py -3.12 log/roadmap/S3/28_make_edits.py            # writes log/roadmap/S3/28_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
TREE = ROOT / "port" / "build" / "S3_28"
BASE = ROOT / "port" / "build" / "S3_28_base"
FILES = [
    "port/include/portsim/sim/terrain_render.h",
    "port/src/sim/terrain_render.cpp",
    "port/src/sim/terrain_live.cpp",
    "port/src/sim/gfx_terrain.cpp",
]
NEW = ["port/test/test_terrain_s3_28.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def norm(b: bytes) -> str:
    return b.decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel in FILES:
        base = norm((BASE / rel).read_bytes())
        mine = norm((TREE / rel).read_bytes())
        a, b = base.splitlines(keepends=True), mine.splitlines(keepends=True)
        fe = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = base
        for _r, old, new in fe:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == mine, rel
        edits += fe
    new_files = {rel: norm((TREE / rel).read_bytes()) for rel in NEW}
    body = ('"""S3.28 edits (generated by log/roadmap/S3/28_make_edits.py; applied by 28_assemble.py after w8_assemble.py):\n'
            "lowerEdgeCorner's draw half (renderTileAtFiveOffsets + enableBlackLight1) as terrain pass kind 5, handed to the backend\n"
            "before the state call (log/roadmap/S3/28_notes.md). EDITS: (path, old, new), each old text exactly once.\"\"\"\n"
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new_files, width=130) + "\n")
    (HERE / "28_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits in", len(FILES), "files,", len(new_files), "new files")


if __name__ == "__main__":
    main()
