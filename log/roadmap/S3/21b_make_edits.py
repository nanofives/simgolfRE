"""S3.21b: anchored edits of the attribute-stepping layer (U-1309, opt-in `#tune 30`), generated from the part-1 state of the three files
(port/build/S3_21_p1, saved after 21_edits.py) to port/build/S3_21; checked by applying them to the part-1 text. Applied by
21b_assemble.py AFTER 21_assemble.py; part 1 stays mergeable alone.

    ~/bin/py -3.12 log/roadmap/S3/21b_make_edits.py            # writes 21b_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_21_p1"
MIRROR = ROOT / "port" / "build" / "S3_21"
OUT = HERE / "21b_edits.py"
FILES = ["port/src/sim/gl_raster.cpp", "port/test/test_gl_raster.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def read(p):
    return p.read_bytes().decode("utf-8")


def main():
    out = []
    for rel in FILES:
        a = read(BASE / rel).splitlines(keepends=True)
        b = read(MIRROR / rel).splitlines(keepends=True)
        for lo, hi, jlo, jhi in M13.hunks(a, b):
            out.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    for rel in FILES:
        t = read(BASE / rel)
        for r, old, new in out:
            if r == rel:
                assert t.count(old) == 1, (rel, old[:80])
                t = t.replace(old, new)
        assert t == read(MIRROR / rel), rel
    # the header is unchanged by 21b
    assert read(BASE / "port/include/portsim/sim/gl_raster.h") == read(MIRROR / "port/include/portsim/sim/gl_raster.h")
    OUT.write_text('"""S3.21b edits (generated by log/roadmap/S3/21b_make_edits.py from port/build/S3_21_p1 -> port/build/S3_21; applied by\n'
                   '21b_assemble.py after 21_assemble.py). EDITS: (path, old, new), each old text exactly once."""\n'
                   "EDITS = " + pprint.pformat(out, width=130) + "\n", encoding="utf-8", newline="\n")
    for rel in FILES:
        print(sum(1 for r, _, _ in out if r == rel), rel)


if __name__ == "__main__":
    main()
