"""S3.11: write log/roadmap/S3/files_w5.txt = the union of the steps' files lists (files_w2.txt, 4c, files_w4.txt, 6, 6b, 5, 5b, 7, 8)
+ every shared file 11_assemble.py edits (the `wrote` lines of 11_assemble_verify.log) + S3.11's own files, minus S3.10's in-place files.
Local-only entries (port/corpus/..., instances/...) are kept with their notes as the steps wrote them.

    ~/bin/py -3.12 log/roadmap/S3/11_files.py"""
import pathlib
import re

S3 = pathlib.Path(__file__).resolve().parent
LISTS = ["files_w2.txt", "4c_files.txt", "files_w4.txt", "6_files.txt", "6b_files.txt", "5_files.txt", "5b_files.txt", "7_files.txt",
         "8_files.txt"]
S310 = {"port/src/sim/gl_raster.cpp", "port/include/portsim/sim/gl_raster.h", "port/test/test_gl_raster.py", "port/test/glraster.py"}
OWN11 = ["log/roadmap/S3/MERGE_w5.md", "log/roadmap/S3/files_w5.txt",
         # S6 log files the regenerated decisions table needs (MERGE_w5.md section 1: put back from I6's prepared_s3w2/)
         "log/roadmap/S6/s3_4b_decisions.tsv (from log/roadmap/merges/I6/prepared_s3w2/s3_4b_decisions.tsv)",
         "log/roadmap/S6/merge_decisions.py (from log/roadmap/merges/I6/prepared_s3w2/merge_decisions.py.with_D53)"]


def main():
    seen, out = set(), []

    def add(p):
        if p and p not in seen and p not in S310:
            seen.add(p)
            out.append(p)

    for name in LISTS:
        for l in (S3 / name).read_text(encoding="utf-8").splitlines():
            add(l.strip())
    for l in (S3 / "11_assemble_verify.log").read_text(encoding="utf-8").splitlines():
        m = re.match(r"wrote (\S+)$", l)
        if m:
            add(m.group(1))
    add("re/port/defect_decisions.tsv")   # regenerated by S6's generator with D53 (not a `wrote` line)
    add("port/src/registry.cpp")   # touched (MSBuild does not track modules.inc), unchanged content
    for p in OWN11:
        add(p)
    for p in sorted(S3.glob("11_*")):
        add("log/roadmap/S3/" + p.name + ("/" if p.is_dir() else ""))
    (S3 / "files_w5.txt").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(len(out), "paths")


if __name__ == "__main__":
    main()
