"""S3.22 (W8.6): turn the mirror port/build/S3_22 into anchored edits (22_edits.py): the removal of the unused gfx body
showCharacterEditor.bio from port/src/sim/gfx_chareditor.cpp (S3.19's editbox family replaced it).

Base: port/build/S3_22_base_src/gfx_chareditor.cpp (the file as `w7_assemble.py --dst S3_22 --commit f2dff003 --plain` made it).

    ~/bin/py -3.12 log/roadmap/S3/22_make_edits.py            # writes 22_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_22_base_src" / "gfx_chareditor.cpp"
MIRROR = ROOT / "port" / "build" / "S3_22" / "port" / "src" / "sim" / "gfx_chareditor.cpp"
REL = "port/src/sim/gfx_chareditor.cpp"

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def text(p):
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n")


def main():
    a = text(BASE).splitlines(keepends=True)
    b = text(MIRROR).splitlines(keepends=True)
    edits = [(REL, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
    t = text(BASE)
    for rel, old, new in edits:
        assert t.count(old) == 1, old[:80]
        t = t.replace(old, new)
    assert t == text(MIRROR)
    body = ('"""S3.22 edits (generated by log/roadmap/S3/22_make_edits.py; applied by 22_assemble.py): removes the gfx body\n'
            'showCharacterEditor.bio. EDITS: (path, old, new), each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = {}\n")
    (HERE / "22_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits")


if __name__ == "__main__":
    main()
