"""S3.32: turn the changes made in the tree port/build/S3_32 into anchored exact-text edits (32_edits.py).

Base of each file: I22's port tree (port/build/I22 = w10_base.py's tree, read only). New files are carried whole in NEW_FILES. Hunks
come from 13_make_edits.py's rule (grown until each old text occurs exactly once in the base); the result is checked by applying
every edit to the base text and comparing with the tree.

    ~/bin/py -3.12 log/roadmap/S3/32_make_edits.py            # writes log/roadmap/S3/32_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
TREE = ROOT / "port" / "build" / "S3_32"
BASE = ROOT / "port" / "build" / "I22"
FILES = [
    "port/src/sim/tick_boot.inc",
    "port/include/portsim/execonst_desc.inc",
    "re/model/f_descriptors.tsv",
]
NEW = ["port/src/sim/tick_boot_surfaces.inc", "port/test/test_boot_surfaces.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def norm(b: bytes) -> str:
    return b.decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel in FILES:
        base = norm((BASE / rel).read_bytes())
        mine = norm((TREE / rel).read_bytes())
        a, b = base.splitlines(keepends=True), mine.splitlines(keepends=True)
        fe = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = base
        for _r, old, new in fe:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == mine, rel
        edits += fe
    new_files = {rel: norm((TREE / rel).read_bytes()) for rel in NEW}
    body = ('"""S3.32 edits (generated by log/roadmap/S3/32_make_edits.py; applied by 32_assemble.py after w10_base.py and the\n'
            "S3.31 / S3.30 layers): the boot's static Surface vtable words (tick_boot.inc BootStaticSurfaces, its table\n"
            "tick_boot_surfaces.inc, the descriptor f_imm_473ab9) and their test (log/roadmap/S3/32_notes.md). EDITS: (path, old, new),\n"
            'each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new_files, width=130) + "\n")
    (HERE / "32_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits in", len(FILES), "files,", len(new_files), "new files")


if __name__ == "__main__":
    main()
