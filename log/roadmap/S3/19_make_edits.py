"""S3.19: turn the edits made in the mirror port/build/S3_19 into anchored exact-text edits (19_edits.py), the 18_make_edits.py way.

The base of each file is its copy in log/roadmap/S3/19_base/ (taken from port/build/S3_19_base = `18_assemble.py --dst
S3_19_base`, i.e. wave 6 + S3.17 + S3.18, before any S3.19 edit). For each file in FILES the line diff base -> mirror is cut into
hunks grown to unique anchors; the result is checked by applying every edit to the base text and comparing with the mirror. New
files are copied whole into 19_new/ (NEW_FILES).

    ~/bin/py -3.12 log/roadmap/S3/19_make_edits.py            # writes log/roadmap/S3/19_edits.py and 19_new/
"""
import importlib.util
import pathlib
import pprint
import shutil

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
BASE = HERE / "19_base"
MIRROR = ROOT / "port" / "build" / "S3_19"
BASE_TREE = ROOT / "port" / "build" / "S3_19_base"
OUT = HERE / "19_edits.py"
NEW = HERE / "19_new"
FILES = [
    "port/src/sim/gfx_text.cpp",
    "port/src/sim/gfx.cpp",
    "port/src/sim/chareditor.cpp",
    "port/src/sim/gfx_families.inc",
]
NEW_FILES = [
    "port/src/sim/gfx_editbox.cpp",
    "port/test/test_gfx_s3_19.py",
]

spec = importlib.util.spec_from_file_location("s3_18_make_edits", HERE / "18_make_edits.py")
M18 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M18)


def main():
    for rel in FILES:
        if (BASE_TREE / rel).exists():
            assert (BASE / rel).read_bytes() == (BASE_TREE / rel).read_bytes(), f"{rel}: 19_base differs from port/build/S3_19_base"
    edits = []
    for rel in FILES:
        a = (BASE / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        b = (MIRROR / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        for lo, hi, jlo, jhi in M18.hunks(a, b):
            edits.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    for rel in FILES:
        t = (BASE / rel).read_text(encoding="utf-8")
        for r, old, new in edits:
            if r != rel:
                continue
            assert t.count(old) == 1, (rel, old[:80])
            assert new not in t or new == old, (rel, "applied twice", new[:80])
            t = t.replace(old, new)
        assert t == (MIRROR / rel).read_text(encoding="utf-8"), rel
    body = ('"""S3.19 edits (generated by log/roadmap/S3/19_make_edits.py from log/roadmap/S3/19_base (= port/build/S3_19_base: wave 6\n'
            '+ S3.17 + S3.18) -> port/build/S3_19; to apply after 18_assemble.py\'s steps). (path, old, new): each old text exactly\n'
            'once. New files: 19_new/."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8")
    for rel in NEW_FILES:
        dst = NEW / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(MIRROR / rel, dst)
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")
    print("edits", len(edits), "->", OUT, "; new", len(NEW_FILES), "->", NEW)


if __name__ == "__main__":
    main()
