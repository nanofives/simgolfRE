"""S3.20: turn the mirror port/build/S3_20 into anchored exact-text edits (20_edits.py), the pattern of 15_make_edits.py.

Base: port/build/S3_20_base = `w7_assemble.py --dst S3_20_base` (the S3 wave 7 combined tree on 37e58e96, byte-equal to S3.9's
port/build/S3_9: `w7_assemble.py --verify`). `diff -rq` of port/ between base and mirror lists exactly the files below. EDITS are the
step's own files, NEW_FILES the new files whole (no shared file: module gl_wgl is already listed in modules.inc by S3.15). Line
ends are compared and written as text; the assembler keeps each target file's own (apply_shared.Root). Checked by applying every edit
to the base text and comparing with the mirror.

    ~/bin/py -3.12 log/roadmap/S3/20_make_edits.py            # writes 20_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_20_base"
MIRROR = ROOT / "port" / "build" / "S3_20"
OUT = HERE / "20_edits.py"
FILES = [
    "port/include/portsim/sim/gl_wgl.h",
    "port/src/sim/gl_wgl.cpp",
    "port/include/portsim/sim/terrain_live.h",
    "port/src/sim/terrain_live.cpp",
    "port/src/sim/gfx_terrain.cpp",
    "port/app/main.cpp",                 # S7 file: the --gl option, the renderer choice and its log line (TerrainGuard::attach)
    "port/test/framegate.py",            # --gl, columns renderer / renderer_reason
    "port/test/test_gl_wgl.py",
    "port/test/test_app_ingame.py",      # the replays draw with the renderer the app's session recorded
    "port/test/test_app_live.py",
]
NEW = ["port/src/sim/gl_wgl_ref.inc", "port/test/test_gl_wgl_selfcheck.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def text(p: pathlib.Path) -> str:
    return p.read_bytes().decode("utf-8").replace("\r\n", "\n")


def make(files):
    out = []
    for rel in files:
        a = text(BASE / rel).splitlines(keepends=True)
        b = text(MIRROR / rel).splitlines(keepends=True)
        mine = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        # applied in order, every anchor must still be found exactly once; when an earlier hunk's new text repeats a later anchor,
        # the file goes as one edit (the whole base text -> the whole mirror text)
        t, ok = text(BASE / rel), True
        for _r, old, new in mine:
            if t.count(old) != 1:
                ok = False
                break
            t = t.replace(old, new)
        out += mine if ok and t == text(MIRROR / rel) else [(rel, text(BASE / rel), text(MIRROR / rel))]
    for rel in files:
        t = text(BASE / rel)
        for r, old, new in out:
            if r == rel:
                assert t.count(old) == 1, (rel, old[:80])
                t = t.replace(old, new)
        assert t == text(MIRROR / rel), rel
    return out


def main():
    edits = make(FILES)
    new = {rel: text(MIRROR / rel) for rel in NEW}
    for rel in NEW:
        assert not (BASE / rel).exists(), rel
    body = ('"""S3.20 edits (generated by log/roadmap/S3/20_make_edits.py from port/build/S3_20_base -> port/build/S3_20; applied by\n'
            '20_assemble.py after w7_assemble.py). EDITS: (path, old, new), each old text exactly once (LF; the assembler keeps the\n'
            'target file\'s own line ends); NEW_FILES: path -> whole text of a file the base does not have."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8", newline="\n")
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")
    for r in NEW:
        print(f"new {r} ({len(new[r])} chars)")


if __name__ == "__main__":
    main()
