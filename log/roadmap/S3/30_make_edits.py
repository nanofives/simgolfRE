"""S3.30: turn the changes made in the tree port/build/S3_30 into anchored exact-text edits (30_edits.py).

Base of each file: the plain wave 10 base, port/build/S3_30_base (`w10_base.py --dst S3_30_base` = I22's port tree). New files are
carried whole in NEW_FILES. Hunks are grown by 13_make_edits.py's rule until each old text occurs exactly once in the base; the result
is checked by applying every edit to the base text and comparing with the tree.

    ~/bin/py -3.12 log/roadmap/S3/30_make_edits.py            # writes log/roadmap/S3/30_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
TREE = ROOT / "port" / "build" / "S3_30"
BASE = ROOT / "port" / "build" / "S3_30_base"
FILES = [
    "re/tools/trace_format.py",
    "re/frida/js/trace_rec.js",
    "re/model/trace_schema.md",
    "port/schemas/trace.md",
    "port/src/sim/tick.cpp",
    "port/src/sim/live.cpp",
    "port/include/portsim/sim/live.h",
]
NEW = ["port/test/test_trace_call.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def norm(b: bytes) -> str:
    return b.decode("utf-8").replace("\r\n", "\n")


def main():
    edits = []
    for rel in FILES:
        base = norm((BASE / rel).read_bytes())
        mine = norm((TREE / rel).read_bytes())
        a, b = base.splitlines(keepends=True), mine.splitlines(keepends=True)
        fe = [(rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])) for lo, hi, jlo, jhi in M13.hunks(a, b)]
        t = base
        for _r, old, new in fe:
            assert t.count(old) == 1, (rel, old[:80])
            t = t.replace(old, new)
        assert t == mine, rel
        edits += fe
    new_files = {rel: norm((TREE / rel).read_bytes()) for rel in NEW}
    body = ('"""S3.30 edits (generated by log/roadmap/S3/30_make_edits.py; applied by 30_assemble.py after w10_base.py): the trace\'s\n'
            "DELIVER kind 7 `call` (an injected call: trace_format.py, trace_rec.js, the schema, tick.cpp's TraceInput, the live core's\n"
            "recording) and its tests (log/roadmap/S3/30_notes.md). EDITS: (path, old, new), each old text exactly once.\"\"\"\n"
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new_files, width=130) + "\n")
    (HERE / "30_edits.py").write_text(body, encoding="utf-8", newline="\n")
    print(len(edits), "edits in", len(FILES), "files,", len(new_files), "new files")


if __name__ == "__main__":
    main()
