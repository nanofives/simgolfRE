"""S3.15: turn the mirror port/build/S3_15 into anchored exact-text edits (15_edits.py), the pattern of 13_make_edits.py.

Base: port/build/S3_15_base = `12_assemble.py --dst S3_15_base --commit ee6efc1d` (the wave 7 base, equal to port/build/I15's tree);
`diff -rq` of port/src, port/include, port/test, port/app and port/CMakeLists.txt between base and mirror lists exactly the files
below. EDITS are the step's own files, SHARED_EDITS the shared file (modules.inc, for the integrator), NEW_FILES the new files whole.
The result is checked by applying every edit to the base text and comparing with the mirror.

    ~/bin/py -3.12 log/roadmap/S3/15_make_edits.py            # writes 15_edits.py and 15_framegate_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_15_base"
MIRROR = ROOT / "port" / "build" / "S3_15"
OUT = HERE / "15_edits.py"
FILES = [
    "port/src/sim/gfx_terrain.cpp",
    "port/src/sim/terrain_live.cpp",
    "port/include/portsim/sim/terrain_live.h",
]
FRAMEGATE = ["port/test/framegate.py"]   # its own file (15_framegate_edits.py): S3.16 edits framegate.py too, the lead merges both
FG_OUT = HERE / "15_framegate_edits.py"
SHARED = ["port/src/sim/modules.inc"]
NEW = ["port/include/portsim/sim/gl_wgl.h", "port/src/sim/gl_wgl.cpp", "port/test/test_gl_wgl.py"]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def make(files):
    out = []
    for rel in files:
        a = (BASE / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        b = (MIRROR / rel).read_text(encoding="utf-8").splitlines(keepends=True)
        for lo, hi, jlo, jhi in M13.hunks(a, b):
            out.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    for rel in files:
        t = (BASE / rel).read_text(encoding="utf-8")
        for r, old, new in out:
            if r == rel:
                assert t.count(old) == 1, (rel, old[:80])
                t = t.replace(old, new)
        assert t == (MIRROR / rel).read_text(encoding="utf-8"), rel
    return out


def main():
    edits, shared = make(FILES), make(SHARED)
    new = {rel: (MIRROR / rel).read_text(encoding="utf-8") for rel in NEW}
    for rel in NEW:
        assert not (BASE / rel).exists(), rel
    body = ('"""S3.15 edits (generated by log/roadmap/S3/15_make_edits.py from port/build/S3_15_base -> port/build/S3_15; applied by\n'
            '15_assemble.py after 12_assemble.py). EDITS / SHARED_EDITS: (path, old, new), each old text exactly once; SHARED_EDITS\n'
            'touch a shared file (modules.inc: one SG_MODULE line); NEW_FILES: path -> whole text of a file the base does not have."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n"
            "SHARED_EDITS = " + pprint.pformat(shared, width=130) + "\n"
            "NEW_FILES = " + pprint.pformat(new, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8")
    fg = make(FRAMEGATE)
    FG_OUT.write_text('"""S3.15 framegate.py edits (generated by 15_make_edits.py; base port/build/S3_15_base): the `--host-gl` option and\n'
                      'run_scenario(host_gl=...). (path, old, new), each old text exactly once; applied by 15_assemble.py after\n'
                      '15_edits.py. None of them touches the snapshot code."""\n'
                      "EDITS = " + pprint.pformat(fg, width=130) + "\n", encoding="utf-8")
    print(f"{len(fg):3d} port/test/framegate.py -> {FG_OUT.name}")
    per = {}
    for r, _, _ in edits + shared:
        per[r] = per.get(r, 0) + 1
    for r in FILES + SHARED:
        print(f"{per.get(r, 0):3d} {r}")
    for r in NEW:
        print(f"new {r} ({len(new[r])} chars)")


if __name__ == "__main__":
    main()
