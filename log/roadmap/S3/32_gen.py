"""S3.32: generate port/src/sim/tick_boot_surfaces.inc, the static Surface objects the CRT's C++ initializers construct, from
log/roadmap/S3/32_logs/static_surfaces.tsv (32_measure.py ctors), as GameState member + offset, count, stride; and add the
Surface_ctor vtable immediate's descriptor row to the tree's re/model/f_descriptors.tsv (then the tree's
re/tools/execonst_gen.py regenerates port/include/portsim/execonst_desc.inc).

    ~/bin/py -3.12 log/roadmap/S3/32_gen.py [--tree S3_32] [--check]

Checks made while generating: every element lies inside its GameState object, no two elements overlap, and the file's
initialised .data holds 0 in each element's first 0x28 bytes (Surface_ctor's stores: the vtable at +0 and zeros at +4..+0x24,
so on the bss only the +0 word changes)."""
from __future__ import annotations

import argparse
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
TSV = ROOT / "log" / "roadmap" / "S3" / "32_logs" / "static_surfaces.tsv"
EXE = ROOT / "original" / "golf_clean.exe"
DATA_VA = 0x004C1000
DESC_ROW = ("f_imm_473ab9\t0x73ab9\t0x4\tptr\t1\t4\t1\tcode_immediate\tSurface_ctor@473ab0\t0x00473ab9\tro\thigh\t0\t"
            "the imm32 of Surface_ctor's `mov dword ptr [eax], imm32` at 0x00473ab7: the vtable word every Surface "
            "(SpriteRef) gets at +0 (S3.32: the boot's static Surface constructions, tick_boot_surfaces.inc)")

HEAD = """// GENERATED by log/roadmap/S3/32_gen.py from log/roadmap/S3/32_logs/static_surfaces.tsv (32_measure.py ctors). Do not edit.
// The Surface objects the CRT's C++ initializers construct before gameMain (__cinit over the initializer table): every
// `mov ecx, <object>; call Surface_ctor`, every ehVectorConstructorIterator(<object>, 0x2c, n, Surface_ctor, ...) and every
// Surface sub-object of an element another constructor builds (Flic::ctorBase's `lea ecx, [esi + 8]`), followed from each
// initializer slot through direct calls and tail jumps. SG_BOOT_SURFACE(GameState member, byte offset in it, count, stride).
// 147 rows, 60,773 elements: equal, one for one, to the words that hold Surface_ctor's vtable word in all 205 segment start
// images (log/roadmap/S3/32_logs/crosscheck.log).
"""


def build(tree: pathlib.Path) -> str:
    sys.path.insert(0, str(ROOT / "log" / "roadmap" / "S3"))
    import importlib.util
    spec = importlib.util.spec_from_file_location("m32", ROOT / "log" / "roadmap" / "S3" / "32_measure.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    objs = {name: (off, size) for off, size, name, cls, ptr in m.objects()}
    exe = EXE.read_bytes()
    import pefile
    pe = pefile.PE(str(EXE), fast_load=True)
    data = next(s for s in pe.sections if s.Name.startswith(b".data"))
    init = exe[data.PointerToRawData:data.PointerToRawData + data.SizeOfRawData]
    lines, spans = [], []
    for l in TSV.read_text().splitlines()[1:]:
        f = l.split("\t")
        va, n, stride, sym = int(f[0], 16), int(f[1]), int(f[2], 16), f[5]
        off, size = objs[sym]
        rel = va - DATA_VA - off
        assert 0 <= rel and rel + (n - 1) * stride + 0x2C <= size, (sym, hex(va))
        for i in range(n):
            e = va - DATA_VA + i * stride
            spans.append((e, e + 0x2C, sym))
            assert not any(init[e:e + 0x28]), (sym, hex(va), i)
        lines.append(f"SG_BOOT_SURFACE({sym}, {rel}, {n}, {stride})")
    spans.sort()
    for a, b in zip(spans, spans[1:]):
        assert a[1] <= b[0], (a, b)
    return HEAD + "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tree", default="S3_32")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    tree = ROOT / "port" / "build" / a.tree
    out = tree / "port" / "src" / "sim" / "tick_boot_surfaces.inc"
    text = build(tree)
    desc = tree / "re" / "model" / "f_descriptors.tsv"
    rows = desc.read_text(encoding="utf-8").split("\n")
    has = any(r.startswith("f_imm_473ab9\t") for r in rows)
    if a.check:
        ok = out.exists() and out.read_text(encoding="utf-8") == text and has
        print("tick_boot_surfaces.inc", "up to date" if ok else "STALE", "/ descriptor row", "present" if has else "MISSING")
        return 0 if ok else 1
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}: {text.count('SG_BOOT_SURFACE(')} rows")
    if not has:
        rows.insert(1, DESC_ROW)   # the table is in va order; this va is below every other row's
        desc.write_text("\n".join(rows), encoding="utf-8", newline="")
        print(f"added f_imm_473ab9 to {desc.relative_to(ROOT)}")
    r = subprocess.run([sys.executable, str(tree / "re" / "tools" / "execonst_gen.py")], cwd=tree)
    return r.returncode


if __name__ == "__main__":
    sys.exit(main())
