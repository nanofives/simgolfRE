"""S3.21: turn the mirror port/build/S3_21 into anchored exact-text edits (21_edits.py), the pattern of 15_make_edits.py.

Base: port/build/S3_21_base = `w7_assemble.py --dst S3_21_base --commit f2dff003 --plain` (f2dff003 holds wave 7); `diff -rq` of
port/src, port/include and port/test between base and mirror lists exactly the three files below. The result is checked by applying
every edit to the base text and comparing with the mirror. No shared file is touched (no modules.inc line: gl_raster is an
existing module).

    ~/bin/py -3.12 log/roadmap/S3/21_make_edits.py            # writes 21_edits.py
"""
import importlib.util
import pathlib
import pprint

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
BASE = ROOT / "port" / "build" / "S3_21_base"
MIRROR = ROOT / "port" / "build" / "S3_21"
OUT = HERE / "21_edits.py"
FILES = [
    "port/src/sim/gl_raster.cpp",
    "port/include/portsim/sim/gl_raster.h",
    "port/test/test_gl_raster.py",
]

spec = importlib.util.spec_from_file_location("m13", HERE / "13_make_edits.py")
M13 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(M13)


def read(p):
    return p.read_bytes().decode("utf-8")


def make(files):
    out = []
    for rel in files:
        a = read(BASE / rel).splitlines(keepends=True)
        b = read(MIRROR / rel).splitlines(keepends=True)
        for lo, hi, jlo, jhi in M13.hunks(a, b):
            out.append((rel, "".join(a[lo:hi]), "".join(b[jlo:jhi])))
    for rel in files:
        t = read(BASE / rel)
        for r, old, new in out:
            if r == rel:
                assert t.count(old) == 1, (rel, old[:80])
                t = t.replace(old, new)
        assert t == read(MIRROR / rel), rel
    return out


def main():
    edits = make(FILES)
    body = ('"""S3.21 edits (generated by log/roadmap/S3/21_make_edits.py from port/build/S3_21_base -> port/build/S3_21; applied by\n'
            '21_assemble.py after `w7_assemble.py --plain`). EDITS: (path, old, new), each old text exactly once."""\n'
            "EDITS = " + pprint.pformat(edits, width=130) + "\n")
    OUT.write_text(body, encoding="utf-8", newline="\n")
    per = {}
    for r, _, _ in edits:
        per[r] = per.get(r, 0) + 1
    for r in FILES:
        print(f"{per.get(r, 0):3d} {r}")


if __name__ == "__main__":
    main()
