"""S4.3: assemble port/src/sim/audio_codec.cpp from the head (log/roadmap/S4/3_parts/head.cpp) and the hand-edited bodies
(log/roadmap/S4/3_parts/body.cpp: one `// ---- <name>` block per function with a `<name>_body` function, the output of
3_xlat.py edited by hand). Each function gets its adapter (argument slots -> the body's parameters, CxScope, negative
control mode 1) and its FuncDef row (hooks.csv name, cdecl, the registry key's return type, the arity, fpcw 0x027f for the
float functions of portsim/sim/audio_codec.h).

    ~/bin/py -3.12 log/roadmap/S4/3_assemble.py [--out port/src/sim/audio_codec.cpp]
"""
import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
HEAD = HERE / "3_parts" / "head.cpp"
BODY = HERE / "3_parts" / "body.cpp"
HDR = ROOT / "port" / "include" / "portsim" / "sim" / "audio_codec.h"
MARK = re.compile(r"^// ---- (\S+)", re.M)

# the dword (offset from the first pointer argument) mode 1 flips for a function that returns nothing
VOID_OFF = {"codecInitEncoderContext": 0x0, "codecInitDecoderContext": 0x0}


def x87_functions():
    t = HDR.read_text()
    blk = t[t.index("kAudioCodecX87Functions"):]
    blk = blk[:blk.index("};")]
    return set(re.findall(r'"(\w+)"', blk))


def split_params(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<(":
            depth += 1
        elif ch in ">)":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def adapter(name, block):
    m = re.search(rf"^(\w+)\s+{re.escape(name)}_body\((.*?)\)\s*\{{", block, re.M | re.S)
    assert m, name
    ret, params = m.group(1), split_params(re.sub(r"/\*.*?\*/|//[^\n]*", "", m.group(2)))
    args = []
    for i, p in enumerate(params):
        if p.startswith("P<"):
            ty = p[:p.rindex(">") + 1]
            args.append(f"{ty}(a[{i}])")
        elif re.match(r"(int|int32_t)\b", p):
            args.append(f"static_cast<int32_t>(a[{i}])")
        elif re.match(r"(unsigned|uint32_t|u32)\b", p):
            args.append(f"a[{i}]")
        else:
            raise SystemExit(f"{name}: parameter {p!r}")
    call = f"{name}_body({', '.join(args)})"
    if ret in ("int", "int32_t"):
        body = f"r.set_i32(static_cast<int32_t>(neg_u32(NEG({name}), static_cast<u32>({call}))));"
    elif ret in ("unsigned", "uint32_t", "u32"):
        body = f"r.set_u32(neg_u32(NEG({name}), {call}));"
    elif ret == "double":
        body = f"const double v = {call};\n  r.set_double(NEG({name}) == 1 ? v + 1.0 : v);"
    elif ret == "void":
        first = next(i for i, p in enumerate(params) if p.startswith("P<"))
        body = f"{call};\n  neg_mem(ctx, NEG({name}), a[{first}] + {VOID_OFF.get(name, 0):#x}u);"
    else:
        raise SystemExit(f"{name}: return {ret!r}")
    rtxt = {"int": "int", "int32_t": "int", "unsigned": "uint32", "uint32_t": "uint32", "u32": "uint32", "double": "double",
            "void": "void"}[ret]
    a = (f"void a_{name}(Ctx &ctx, const uint32_t *a, Ret &r) {{\n  const CxScope s(ctx);\n  {body}\n}}\n")
    a = a.replace("Ret &r) {\n  const CxScope s(ctx);\n  " + call + ";", "Ret &) {\n  const CxScope s(ctx);\n  " + call + ";") \
        if ret == "void" else a
    return a, rtxt, len(params)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "port" / "src" / "sim" / "audio_codec.cpp"))
    a = ap.parse_args()
    text = BODY.read_text()
    ms = list(MARK.finditer(text))
    x87 = x87_functions()
    blocks, table = [], []
    for i, m in enumerate(ms):
        end = ms[i + 1].start() if i + 1 < len(ms) else len(text)
        name, block = m.group(1), text[m.start():end].rstrip("\n") + "\n"
        ad, rtxt, n = adapter(name, block)
        blocks.append(block + ad)
        fpcw = "0x027f" if name in x87 else "0"
        table.append(f'    {{"{name}", "default", "{rtxt}", {n}, {fpcw}, a_{name}, &g_negctl_{name}}},')
    pre = text[:ms[0].start()] if ms else ""
    pre = "\n".join(ln for ln in pre.split("\n") if not ln.startswith("// generated by"))
    names = [MARK.match(text[m.start():]).group(1) for m in ms]
    negs = "// negative-control modes (0 = the correct body; mode 1 every function, mode 2 the spill controls)\n" + \
        "".join(f"int g_negctl_{n} = 0;\n" for n in names)
    out = [HEAD.read_text().rstrip("\n").rsplit("}  // namespace", 1)[0], negs, pre] + blocks
    out.append("const FuncDef kFuncs[] = {\n" + "\n".join(table) + "\n};\n\n}  // namespace\n\n"
               "extern const ModuleDef kModule_audio_codec = {\"audio_codec\", kFuncs, sizeof(kFuncs) / sizeof(kFuncs[0])};\n\n"
               "}  // namespace portsim\n")
    t = "\n".join(out)
    pathlib.Path(a.out).write_text(t)
    print(f"{len(blocks)} functions, {len(t.splitlines())} lines -> {a.out}")


if __name__ == "__main__":
    main()
