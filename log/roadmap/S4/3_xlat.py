"""S4.3: carry the 42 hook bodies (shim/src/re/c3*.cpp detours of the S4.3 rows) over to port syntax, mechanically.

Host pointers become virtual pointers (P<T>, portsim audio_codec head), the hook's helpers become the head's, callee function
pointers become dispatcher calls, the c3bv frame idiom becomes CodecFrame, DLL VAs in comments become rvas. The output
(log/roadmap/S4/3_conv/audio_codec_x.cpp) is one `// ---- <name>` block per function with a `_body` function; it is the
starting point of the hand edits (3_assemble.py takes the edited blocks from log/roadmap/S4/3_parts/body.cpp).

    ~/bin/py -3.12 log/roadmap/S4/3_xlat.py
"""
import csv
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import importlib  # noqa: E402

X = importlib.import_module("3_extract")

TYPES = r"(?:unsigned\s+short|unsigned\s+char|signed\s+char|unsigned\s+int|unsigned|short|int|float|double|char|void)"
TMAP = {"unsigned short": "uint16_t", "unsigned char": "uint8_t", "signed char": "int8_t", "unsigned int": "uint32_t",
        "unsigned": "uint32_t", "short": "int16_t", "int": "int32_t", "float": "float", "double": "double", "char": "char",
        "void": "char"}


def ptype(t):
    return TMAP[re.sub(r"\s+", " ", t.strip())]


def typedef_rets(src_text):
    """typedef R(__cdecl* Name)(...) -> {Name: R}"""
    out = {}
    for m in re.finditer(r"typedef\s+([\w\s\*]+?)\s*\(\s*__\w+\s*\*\s*(\w+)\s*\)", src_text):
        out[m.group(2)] = m.group(1).strip()
    return out


def va2rva(m):
    v = int(m.group(0), 16)
    if 0x10001000 <= v < 0x10200000:
        return f"0x{v - 0x10000000:x}"
    return m.group(0)


def xlat(text, rets):
    t = text
    # the c3bv frame idiom
    t = re.sub(r"const unsigned FRAME = (0x[0-9A-Fa-f]+);[^\n]*\n\s*unsigned int rawFrame\[[^\n]*\n\s*memset\(rawFrame[^\n]*\n"
               r"\s*memset\(reinterpret_cast<char\*>\(rawFrame\)[^\n]*\n\s*char\* const ebp = [^\n]*\n",
               r"const CodecFrame fr(cx(), \1);  // the original's frame, 0xcc-filled\n    const P<char> ebp = fr.ebp();\n", t)
    # callee function pointers: `Name_t var = reinterpret_cast<Name_t>(c3xx_sound(0x...));`
    def callee(m):
        ty, var, rva = m.group(1), m.group(2), m.group(3)
        f = rets.get(ty, "int") in ("double", "float")
        fn = "ccall_f" if f else "ccall"
        return f"const auto {var} = [](const auto &... a) {{ return {fn}({rva}, a...); }};"
    t = re.sub(r"(\w+_t)\s+(\w+)\s*=\s*reinterpret_cast<\1>\(\s*c3\w+_sound\((0x[0-9A-Fa-f]+)\)\s*\);", callee, t)
    t = re.sub(r"(\w+_t)\s+(\w+)\s*=\s*c3\w+_fn<\1>\((0x[0-9A-Fa-f]+)\);", callee, t)

    def inline_callee(m):
        ty, rva = m.group(1), m.group(2)
        f = rets.get(ty, "int") in ("double", "float")
        return f"[](const auto &... a) {{ return {'ccall_f' if f else 'ccall'}({rva}, a...); }}"
    t = re.sub(r"reinterpret_cast<(\w+_t)>\(\s*c3\w+_sound\((0x[0-9A-Fa-f]+)\)\s*\)", inline_callee, t)
    t = re.sub(r"const_cast<[^>]*>", "", t)
    def fn_call(m):
        f = rets.get(m.group(1), "int") in ("double", "float")
        return f"{'ccall_f' if f else 'ccall'}({m.group(2)}, "
    t = re.sub(r"c3\w\w_fn<(\w+)>\((0x[0-9A-Fa-f]+)\)\(", fn_call, t)
    t = re.sub(r"(ccall(?:_f)?\(0x[0-9A-Fa-f]+), \)", r"\1)", t)
    # helpers
    t = re.sub(r"\bc3\w\w_sound\(", "sva(", t)
    t = re.sub(r"\bc3\w\w_f\(", "rf(", t)
    t = re.sub(r"\bc3\w\w_d\(", "rd(", t)
    t = re.sub(r"\bc3\w\w_i\(", "ri(", t)
    t = re.sub(r"\bc3\w\w_copy32\(", "copy32(", t)
    t = re.sub(r"\bc3\w\w_ftol\(", "ftol(", t)
    t = re.sub(r"\bc3\w\w_sqrt\(", "crt_sqrt(", t)
    t = re.sub(r"\bc3\w\w_log\(", "crt_log(", t)
    t = re.sub(r"\bc3\w\w_exp\(", "crt_exp(", t)
    t = re.sub(r"\bc3\w\w_srem\(", "srem(", t)
    t = re.sub(r"\bc3\w\w_bits\(", "fbits(", t)
    t = re.sub(r"\bc3\w\w_loc<", "loc<", t)
    # casts between pointer types
    t = re.sub(rf"(?:reinterpret_cast|static_cast)<\s*(?:const\s+)?({TYPES})\s*\*\s*(?:const\s*)?>\(",
               lambda m: f"pc<{ptype(m.group(1))}>(", t)
    # pointer declarations
    t = re.sub(rf"\b(?:const\s+)?({TYPES})\s*\*\s*(?:const\s+)?(?=[\w)])", lambda m: f"P<{ptype(m.group(1))}> ", t)
    # DLL VAs in comments -> rvas
    t = re.sub(r"0x[0-9A-Fa-f]{8}", va2rva, t)
    t = t.replace("__cdecl ", "")
    return t


def main():
    out = ["// generated by log/roadmap/S4/3_xlat.py from the hook sources (see its header)\n"]
    srcs = {}
    for r in X.rows:
        rva = int(r["rva"], 16)
        src = r["hook_source"]
        if src not in srcs:
            srcs[src] = (ROOT / "shim/src/re" / src).read_text()
        det, k, i, j = X.find(rva, src)
        lines = srcs[src].split("\n")
        doc = [ln for ln in lines[k - 1:i - 1] if ln.startswith("//")]
        body = "\n".join(lines[i - 1:j])
        body = re.sub(rf"\b{det}\(", f"{r['name']}_body(", body, count=1)
        rets = typedef_rets(srcs[src])
        out.append(f"// ---- {r['name']} (rva {r['rva']}): from {src} {det}\n" + xlat("\n".join(doc), rets) + "\n"
                   + xlat(body, rets) + "\n")
    p = HERE / "3_conv" / "audio_codec_x.cpp"
    p.write_text("\n".join(out))
    print(p, sum(len(o.split("\n")) for o in out), "lines")


if __name__ == "__main__":
    main()
