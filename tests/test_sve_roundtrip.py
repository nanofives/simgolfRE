"""Static checks of the .sve field table (re/model/sve_fields.tsv) and the ctypes mirror (re/model/model_ctypes.py,
generated by re/tools/model_ctypes_gen.py) against re/tools/sve.py, plus a value-level round trip of the save fixtures.
Stream G2 of re/PHASE1_PLAN.md; report re/analysis/data/model_sve.md."""
import csv
import re
import sys

import pytest

import sve
from conftest import GAME_DIR, ROOT

pytestmark = pytest.mark.static

sys.path.insert(0, str(ROOT / "re" / "model"))
import model_ctypes as M  # noqa: E402
import model_ctypes_gen as GEN  # noqa: E402  (re/tools is on the path through conftest)

TABLE_PATH = ROOT / "re" / "model" / "sve_fields.tsv"
TABLE = M.load_field_table(TABLE_PATH)
ROWS = list(csv.DictReader(TABLE_PATH.open(newline="", encoding="utf-8"), delimiter="\t"))
FIXTURES = [ROOT / "tests" / "fixtures" / "stories" / f"{n}.sve" for n in ("mood5", "stories5", "stories9")]


def test_field_table_matches_sve_py():
    expect = [("H0", "header", 0x0051A068, sve.HEADER_LEN), ("H1", "header2", 0x0051A068, sve.HEADER_LEN)]
    expect += [(str(i), "body", va, n) for i, (va, n) in enumerate(sve.FIELDS)]
    expect += [("tailA", "tailA", va, n) for va, n in sve.TAIL_A[1]]
    expect += [(f"tailB{k}", "tailB", va, n) for k, (va, n) in enumerate(sve.TAIL_B[1])]
    got = [(r["index"], r["part"], int(r["va"], 16), int(r["size"], 16)) for r in ROWS]
    assert got == expect
    flags_index = str([va for va, _ in sve.FIELDS].index(sve.FLAGS_VA))
    for r in TABLE:
        if r["part"] == "tailA":
            assert (r["mask"], r["flag_field"]) == (sve.TAIL_A[0], flags_index)
        elif r["part"] == "tailB":
            assert (r["mask"], r["flag_field"]) == (sve.TAIL_B[0], flags_index)
        else:
            assert r["mask"] is None


def test_field_table_offsets():
    off = sve.HEADER_LEN
    for r in ROWS:
        if r["part"] in ("header", "header2"):
            continue
        assert int(r["file_offset"], 16) == off, r["index"]
        off += int(r["size"], 16)


def test_field_table_symbols_resolve_in_the_mirror():
    for row, raw in zip(TABLE, ROWS):
        assert raw["status"] in ("named", "placeholder", "partial", "unnamed")
        if raw["mapping"] == "none":
            assert row["members"] == [] and raw["status"] == "unnamed"
            continue
        end = 0
        for sym, off in row["members"]:
            assert off >= end, (row["index"], sym)
            end = off + M.ctypes.sizeof(M.ctype(sym))
        assert end <= row["size"], row["index"]
        if raw["mapping"] in ("exact", "slice"):
            assert end == row["size"], row["index"]
        parts = M.field_parts(row, bytes(row["size"]))
        assert sum(len(v) for _k, v in parts) == row["size"]


def test_mirror_is_current_and_checked():
    src, model, _syms, errs, _notes = GEN.build()
    assert errs == []                       # every static assert and +0xNN offset comment of the headers holds
    assert len(model.asserts) > 0
    assert (ROOT / "re" / "model" / "model_ctypes.py").read_text(encoding="utf-8") == src, \
        "re/model/model_ctypes.py is stale: rerun re/tools/model_ctypes_gen.py"


def test_mirror_embeds_no_original_address():
    text = (ROOT / "re" / "model" / "model_ctypes.py").read_text(encoding="utf-8")
    for h in re.findall(r"\b0x([0-9a-fA-F]+)\b", text):
        v = int(h, 16)
        assert not (0x00400000 <= v < 0x00900000 or 0x10000000 <= v < 0x10200000), hex(v)


@pytest.mark.parametrize("path", FIXTURES, ids=lambda p: p.name)
def test_fixture_value_roundtrip(path):
    if not path.exists():
        pytest.skip(f"{path.name}: game-derived fixture not present (tests/fixtures/stories/README.md)")
    blob = path.read_bytes()
    headers, parts = M.split_sve(blob, TABLE)
    vparts, changed = M.value_roundtrip(parts)
    assert changed == []                    # every byte belongs to a member of its type
    assert M.join_sve(headers, vparts, TABLE) == blob
    s = sve.parse(blob)
    rows = M.body_layout(TABLE, s.field(sve.FLAGS_VA).u32())
    assert len(rows) == len(s.fields)
    for r, f in zip(rows, s.fields):
        assert b"".join(v for _k, v in M.field_parts(r, f.data)) == f.data


def test_top10_value_roundtrip():
    p = GAME_DIR / "top10.sve"
    if not p.exists():
        pytest.skip("top10.sve not present in the install copy")
    blob = p.read_bytes()
    o = M.view("g_topScores", blob)          # mainLoop writes the 0x618-byte TopScore[10] table as the whole file
    assert bytes(M.from_values("g_topScores", M.as_dict(o))) == blob
